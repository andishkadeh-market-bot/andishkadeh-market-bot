def psychology_chapter_text(chapter):

    text = PSYCHOLOGY_CHAPTER_TEXTS.get(chapter)

    if not text:
        return (
            "❌ فصل موردنظر پیدا نشد.",
            psychology_back_menu()
        )

    keyboard = [
        [
            InlineKeyboardButton(
                "📝 آزمون این فصل",
                callback_data=f"psychology_exam_intro_{chapter}"
            )
        ],
        [
            InlineKeyboardButton(
                "🔙 روانشناسی و مددکاری",
                callback_data="psychology_socialwork"
            )
        ],
        [
            InlineKeyboardButton(
                "🏠 منوی اصلی",
                callback_data="home"
            )
        ]
    ]

    return text, InlineKeyboardMarkup(keyboard)


