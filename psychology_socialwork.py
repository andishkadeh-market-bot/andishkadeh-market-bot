def psychology_exam_result(
    chapter,
    score
):

    questions = PSYCHOLOGY_CHAPTER_QUESTIONS.get(
        chapter,
        []
    )

    total = len(questions)

    if total == 0:

        return (
            "❌ آزمونی برای این فصل وجود ندارد.",
            psychology_back_menu()
        )

    wrong = total - score

    percentage = round(
        (score / total) * 100
    )

    if percentage >= 90:

        evaluation = "🏆 فوق‌العاده"
        message = "تسلط شما بر این فصل بسیار عالی است."

    elif percentage >= 80:

        evaluation = "🥇 عالی"
        message = "دانش بسیار خوبی دارید."

    elif percentage >= 70:

        evaluation = "🥈 خوب"
        message = "مباحث اصلی را به خوبی یاد گرفته‌اید."

    elif percentage >= 50:

        evaluation = "🟡 متوسط"
        message = "برخی مفاهیم نیاز به مرور دارند."

    else:

        evaluation = "📚 نیازمند مطالعه"
        message = "پیشنهاد می‌شود درسنامه را دوباره مطالعه کنید."

    keyboard = []

    if chapter < 12:

        keyboard.append([
            InlineKeyboardButton(
                f"📘 فصل بعد: {chapter + 1}",
                callback_data=f"psychology_chapter_{chapter + 1}"
            )
        ])

    keyboard.extend([
        [
            InlineKeyboardButton(
                "🔁 مرور فصل",
                callback_data=f"psychology_chapter_{chapter}"
            )
        ],
        [
            InlineKeyboardButton(
                "🧠 روانشناسی و مددکاری",
                callback_data="psychology_socialwork"
            )
        ],
        [
            InlineKeyboardButton(
                "🏠 منوی اصلی",
                callback_data="home"
            )
        ]
    ])

    text = f"""
🏁 آزمون فصل {chapter} پایان یافت.

{CHAPTER_ICONS.get(chapter, "📚")}
{CHAPTER_NAMES.get(chapter)}

━━━━━━━━━━━━━━━━━━━━

📊 نتیجه

📝 تعداد سؤالات: {total}

✅ صحیح: {score}

❌ غلط: {wrong}

📈 درصد: {percentage}٪

🎯 ارزیابی:
{evaluation}

━━━━━━━━━━━━━━━━━━━━

💡 {message}

━━━━━━━━━━━━━━━━━━━━

🏛️ اندیشکده مدیریت و بازار
"""

    return text, InlineKeyboardMarkup(keyboard)


