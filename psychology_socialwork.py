def psychology_exam_question(
    chapter,
    index=0,
    score=0
):

    questions = PSYCHOLOGY_CHAPTER_QUESTIONS.get(
        chapter,
        []
    )

    if not questions:

        return (
            "❌ سوالی برای این فصل وجود ندارد.",
            psychology_back_menu()
        )

    if index >= len(questions):

        index = 0

    question = questions[index]

    text = f"""
📝 آزمون روانشناسی و مددکاری

📘 فصل {chapter}
{CHAPTER_ICONS.get(chapter, "📚")} {CHAPTER_NAMES.get(chapter)}

━━━━━━━━━━━━━━━━━━━━

❓ سؤال {index + 1} از {len(questions)}

⭐ امتیاز فعلی: {score}

━━━━━━━━━━━━━━━━━━━━

{question["question"]}

━━━━━━━━━━━━━━━━━━━━

👇 گزینه صحیح را انتخاب کنید:
"""

    keyboard = []

    for i, option in enumerate(question["options"]):

        keyboard.append([
            InlineKeyboardButton(
                option,
                callback_data=(
                    f"psychology_answer_"
                    f"{chapter}_"
                    f"{index}_"
                    f"{i}_"
                    f"{score}"
                )
            )
        ])

    keyboard.append([
        InlineKeyboardButton(
            "🧠 خروج از آزمون",
            callback_data="psychology_socialwork"
        )
    ])

    return text, InlineKeyboardMarkup(keyboard)


