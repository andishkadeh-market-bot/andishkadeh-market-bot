# 🏠 منوی اصلی روانشناسی و مددکاری
# =========================================================

def psychology_menu():

    keyboard = []

    for chapter, name in CHAPTER_NAMES.items():

        keyboard.append([
            InlineKeyboardButton(
                f"{CHAPTER_ICONS.get(chapter, '📚')} "
                f"فصل {chapter} | {name}",
                callback_data=f"psychology_chapter_{chapter}"
            )
        ])

    keyboard.append([
        InlineKeyboardButton(
            "🏆 آزمون جامع روانشناسی و مددکاری",
            callback_data="psychology_full_exam"
        )
    ])

    keyboard.append([
        InlineKeyboardButton(
            "🏠 منوی اصلی",
            callback_data="home"
        )
    ])

    return InlineKeyboardMarkup(keyboard)


