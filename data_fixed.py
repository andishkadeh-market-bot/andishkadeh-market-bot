def search_management(query: str) -> list[dict]:
    """Search chapters, lessons and educational metadata."""
    query = str(query or "").strip().casefold()

    if not query:
        return []

    results: list[dict] = []

    for chapter in MANAGEMENT_CHAPTERS:
        if not isinstance(chapter, dict):
            continue

        chapter_id = str(chapter.get("id", ""))
        chapter_title = str(chapter.get("title", ""))
        chapter_description = str(
            chapter.get("description", "")
        )

        chapter_text = " ".join(
            [
                chapter_id,
                chapter_title,
                chapter_description,
            ]
        )

        if query in chapter_text.casefold():
            results.append(
                {
                    "type": "chapter",
                    "chapter_id": chapter_id,
                    "title": chapter_title,
                }
            )

        lessons = chapter.get("lessons", [])

        if not isinstance(lessons, list):
            continue

        for lesson in lessons:
            if not isinstance(lesson, dict):
                continue

            searchable: list[str] = [
                str(lesson.get("id", "")),
                str(lesson.get("title", "")),
                str(lesson.get("content", "")),
            ]

            for key in (
                "subtopics",
                "specialized_tips",
                "exam_tips",
                "examples",
                "keywords",
                "review",
            ):
                values = lesson.get(key, [])

                if isinstance(values, list):
                    for value in values:
                        if isinstance(value, dict):
                            searchable.extend(
                                [
                                    str(value.get("title", "")),
                                    str(value.get("text", "")),
                                    str(value.get("description", "")),
                                ]
                            )
                        else:
                            searchable.append(str(value))

                elif values:
                    searchable.append(str(values))

            searchable_text = " ".join(searchable)

            if query in searchable_text.casefold():
                results.append(
                    {
                        "type": "lesson",
                        "chapter_id": chapter_id,
                        "lesson_id": str(
                            lesson.get("id", "")
                        ),
                        "title": lesson.get(
                            "title",
                            lesson.get("id", ""),
                        ),
                    }
                )

    return results


