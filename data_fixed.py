# Module Health Check
# ==========================================================

def management_data_health_check() -> bool:
    """Validate the basic integrity of the Management curriculum data."""
    try:
        if not isinstance(MANAGEMENT_CHAPTERS, list):
            return False

        if not MANAGEMENT_CHAPTERS:
            return False

        chapter_ids: set[str] = set()

        for chapter in MANAGEMENT_CHAPTERS:
            if not isinstance(chapter, dict):
                return False

            chapter_id = chapter.get("id")

            if not chapter_id:
                return False

            chapter_id = str(chapter_id)

            if chapter_id in chapter_ids:
                return False

            chapter_ids.add(chapter_id)

            if not isinstance(
                chapter.get("title", ""),
                str,
            ):
                return False

            lessons = chapter.get("lessons", [])

            if not isinstance(lessons, list):
                return False

            lesson_ids: set[str] = set()

            for lesson in lessons:
                if not isinstance(lesson, dict):
                    return False

                lesson_id = lesson.get("id")

                if not lesson_id:
                    return False

                lesson_id = str(lesson_id)

                if lesson_id in lesson_ids:
                    return False

                lesson_ids.add(lesson_id)

                if not isinstance(
                    lesson.get("title", ""),
                    str,
                ):
                    return False

                if not isinstance(
                    lesson.get("content", ""),
                    str,
                ):
                    return False

                quiz = lesson.get("quiz", [])

                if not isinstance(quiz, list):
                    return False

                for question in quiz:
                    if not isinstance(question, dict):
                        return False

                    if not question.get("question"):
                        return False

                    options = question.get("options", [])

                    if not isinstance(options, list):
                        return False

                    if len(options) < 2:
                        return False

                    correct_index = question.get("correct_index")

                    if not isinstance(correct_index, int):
                        return False

                    if not (
                        0 <= correct_index < len(options)
                    ):
                        return False

        return True

    except Exception:
        return False


