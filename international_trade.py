def international_trade_result_text(
    chapter,
    score
):

    questions = TRADE_CHAPTER_QUESTIONS.get(
        chapter,
        []
    )

    total = len(questions)

    if total == 0:
        return "❌ آزمونی برای این فصل وجود ندارد."

    percentage = round(
        (score / total) * 100
    )

    wrong = total - score

    if percentage >= 90:

        evaluation = "🏆 فوق‌العاده"

    elif percentage >= 80:

        evaluation = "🥇 عالی"

    elif percentage >= 70:

        evaluation = "🥈 خوب"

    elif percentage >= 50:

        evaluation = "🟡 متوسط"

    else:

        evaluation = "📚 نیازمند مطالعه"

    return f"""
🏁 آزمون فصل {chapter} به پایان رسید.

🌍 {CHAPTER_NAMES.get(chapter)}

━━━━━━━━━━━━━━━━━━

📊 نتیجه

📝 تعداد سؤالات: {total}

✅ صحیح: {score}

❌ غلط: {wrong}

📈 درصد: {percentage}٪

🎯 ارزیابی:
{evaluation}

━━━━━━━━━━━━━━━━━━

📚 پیشنهاد:

درسنامه فصل را مرور کنید،
سپس آزمون را دوباره انجام دهید.
"""


