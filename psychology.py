def psychology_exam_result_text(
    chapter,
    score
):

    questions = PSYCHOLOGY_QUESTIONS.get(
        chapter,
        []
    )

    total = len(questions)

    if total == 0:

        return (
            "❌ آزمونی برای این فصل وجود ندارد.",
            psychology_back_menu()
        )

    wrong = total - score

    percentage = round(
        (score / total) * 100
    )

    if percentage >= 90:

        evaluation = "🏆 فوق‌العاده"

        message = (
            "تسلط شما بر مفاهیم این فصل بسیار عالی است."
        )

    elif percentage >= 80:

        evaluation = "🥇 عالی"

        message = (
            "تسلط بسیار خوبی روی مباحث فصل دارید."
        )

    elif percentage >= 70:

        evaluation = "🥈 خوب"

        message = (
            "عملکرد خوبی دارید، اما مرور بیشتر "
            "باعث تثبیت مطالب می‌شود."
        )

    elif percentage >= 50:

        evaluation = "🟡 متوسط"

        message = (
            "بعضی مفاهیم نیاز به مطالعه و تمرین بیشتری دارند."
        )

    else:

        evaluation = "📚 نیازمند مطالعه"

        message = (
            "پیشنهاد می‌شود ابتدا درسنامه را دوباره "
            "مطالعه کرده و سپس آزمون را تکرار کنید."
        )

    text = f"""
🏁 آزمون فصل {chapter} به پایان رسید.

🧠 {CHAPTER_NAMES[chapter]}

━━━━━━━━━━━━━━━━━━

📊 نتیجه آزمون

📝 تعداد سؤالات: {total}

✅ پاسخ صحیح: {score}

❌ پاسخ غلط: {wrong}

📈 درصد: {percentage}٪

🎯 ارزیابی:

{evaluation}

━━━━━━━━━━━━━━━━━━

💡 {message}

━━━━━━━━━━━━━━━━━━

🎯 مسیر پیشنهادی:

مطالعه
+
تمرین
+
آزمون
+
تحلیل اشتباهات
+
مرور
"""

    keyboard = [

        [
            InlineKeyboardButton(
                "🔄 تکرار آزمون",
                callback_data=f"psychology_exam_{chapter}_0_0"
            )
        ],

        [
            InlineKeyboardButton(
                "📖 مرور فصل",
                callback_data=f"psychology_chapter_{chapter}"
            )
        ],

    ]

    if chapter < len(CHAPTER_NAMES):

        keyboard.append(
            [
                InlineKeyboardButton(
                    f"📘 فصل {chapter + 1}",
                    callback_data=f"psychology_chapter_{chapter + 1}"
                )
            ]
        )

    keyboard.extend(
        [

            [
                InlineKeyboardButton(
                    "🧠 روانشناسی و مددکاری",
                    callback_data="psychology_socialwork"
                )
            ],

            [
                InlineKeyboardButton(
                    "🏠 منوی اصلی",
                    callback_data="home"
                )
            ],

        ]
    )

    return (
        text,
        InlineKeyboardMarkup(keyboard)
    )


