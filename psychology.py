def psychology_section_text(section):

    if section not in PSYCHOLOGY_SECTION_TEXTS:

        return (
            "❌ بخش موردنظر پیدا نشد.",
            psychology_back_menu()
        )

    text = PSYCHOLOGY_SECTION_TEXTS[section]

    keyboard = [

        [
            InlineKeyboardButton(
                "📝 آزمون این بخش",
                callback_data=f"psychology_exam_intro_{section}"
            )
        ],

        [
            InlineKeyboardButton(
                "⬅️ بخش قبل",
                callback_data=(
                    f"psychology_section_{section - 1}"
                    if section > 1
                    else "psychology_socialwork"
                )
            ),
            InlineKeyboardButton(
                "بخش بعد ➡️",
                callback_data=(
                    f"psychology_section_{section + 1}"
                    if section < len(PSYCHOLOGY_SECTIONS)
                    else "psychology_socialwork"
                )
            )
        ],

        [
            InlineKeyboardButton(
                "🧠 روانشناسی و مددکاری",
                callback_data="psychology_socialwork"
            )
        ],

        [
            InlineKeyboardButton(
                "🏠 منوی اصلی",
                callback_data="home"
            )
        ]

    ]

    return text, InlineKeyboardMarkup(keyboard)


