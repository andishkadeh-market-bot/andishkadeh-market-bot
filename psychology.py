def psychology_topic_text(topic):

    if topic not in PSYCHOLOGY_TOPIC_TEXTS:

        return (
            "❌ موضوع موردنظر پیدا نشد.",
            psychology_back_menu()
        )

    text = PSYCHOLOGY_TOPIC_TEXTS[topic]

    keyboard = [

        [
            InlineKeyboardButton(
                "📝 آزمون این بخش",
                callback_data=f"psychology_exam_intro_{topic}"
            )
        ],

        [
            InlineKeyboardButton(
                "⬅️ بخش قبل",
                callback_data=(
                    f"psychology_topic_{topic - 1}"
                    if topic > 1
                    else "psychology_socialwork"
                )
            ),

            InlineKeyboardButton(
                "بخش بعد ➡️",
                callback_data=(
                    f"psychology_topic_{topic + 1}"
                    if topic < 12
                    else "psychology_socialwork"
                )
            )
        ],

        [
            InlineKeyboardButton(
                "🧠 روانشناسی و مددکاری",
                callback_data="psychology_socialwork"
            )
        ],

        [
            InlineKeyboardButton(
                "🏠 منوی اصلی",
                callback_data="home"
            )
        ]

    ]

    return text, InlineKeyboardMarkup(keyboard)


