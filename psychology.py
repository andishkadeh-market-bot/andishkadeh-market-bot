def psychology_exam_result(
    section,
    score
):

    questions = PSYCHOLOGY_QUESTIONS.get(
        section,
        []
    )

    total = len(questions)

    if total == 0:

        return (
            "❌ آزمونی برای این بخش وجود ندارد.",
            psychology_back_menu()
        )

    wrong = total - score

    percentage = round(
        (score / total) * 100
    )

    if percentage >= 90:

        evaluation = "🏆 فوق‌العاده"
        message = (
            "تسلط بسیار خوبی بر مفاهیم این بخش دارید."
        )

    elif percentage >= 80:

        evaluation = "🥇 عالی"
        message = (
            "سطح یادگیری شما بسیار مناسب است."
        )

    elif percentage >= 70:

        evaluation = "🥈 خوب"
        message = (
            "دانش شما مناسب است، اما مرور بیشتر پیشنهاد می‌شود."
        )

    elif percentage >= 50:

        evaluation = "🟡 متوسط"
        message = (
            "برخی مفاهیم نیاز به مطالعه و تمرین بیشتر دارند."
        )

    else:

        evaluation = "📚 نیازمند مطالعه"
        message = (
            "پیشنهاد می‌شود ابتدا درسنامه را دوباره مطالعه کنید."
        )

    text = f"""
🏁 آزمون به پایان رسید.

🧠 {PSYCHOLOGY_SECTIONS.get(
    section,
    {"title": "روانشناسی"}
)["title"]}

━━━━━━━━━━━━━━━━━━

📊 نتیجه

📝 تعداد سؤالات: {total}

✅ پاسخ صحیح: {score}

❌ پاسخ غلط: {wrong}

📈 درصد: {percentage}٪

🎯 ارزیابی:
{evaluation}

━━━━━━━━━━━━━━━━━━

💡 {message}

━━━━━━━━━━━━━━━━━━
"""

    keyboard = [

        [
            InlineKeyboardButton(
                "🔄 تکرار آزمون",
                callback_data=f"psychology_exam_{section}_0_0"
            )
        ],

        [
            InlineKeyboardButton(
                "📖 مرور درسنامه",
                callback_data=f"psychology_section_{section}"
            )
        ],

    ]

    if section < len(PSYCHOLOGY_SECTIONS):

        keyboard.append(
            [
                InlineKeyboardButton(
                    "📘 بخش بعدی",
                    callback_data=(
                        f"psychology_section_{section + 1}"
                    )
                )
            ]
        )

    keyboard.extend(
        [

            [
                InlineKeyboardButton(
                    "🧠 روانشناسی و مددکاری",
                    callback_data="psychology_socialwork"
                )
            ],

            [
                InlineKeyboardButton(
                    "🏠 منوی اصلی",
                    callback_data="home"
                )
            ]

        ]
    )

    return text, InlineKeyboardMarkup(keyboard)


