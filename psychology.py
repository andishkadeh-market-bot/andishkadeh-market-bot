def psychology_exam_question(
    section,
    index=0,
    score=0
):

    questions = PSYCHOLOGY_QUESTIONS.get(
        section,
        []
    )

    if not questions:

        return (
            "❌ سؤالی برای این بخش وجود ندارد.",
            psychology_back_menu()
        )

    if index >= len(questions):
        index = 0

    question = questions[index]

    section_name = PSYCHOLOGY_SECTIONS.get(
        section,
        {"title": "روانشناسی"}
    )["title"]

    text = f"""
📝 آزمون روانشناسی و مددکاری

📚 بخش {section}
{section_name}

━━━━━━━━━━━━━━━━━━

❓ سؤال {index + 1} از {len(questions)}

⭐ امتیاز فعلی: {score}

━━━━━━━━━━━━━━━━━━

{question["question"]}

━━━━━━━━━━━━━━━━━━

👇 گزینه صحیح را انتخاب کنید:
"""

    keyboard = []

    for option_index, option in enumerate(
        question["options"]
    ):

        keyboard.append(
            [
                InlineKeyboardButton(
                    option,
                    callback_data=(
                        f"psychology_answer_"
                        f"{section}_"
                        f"{index}_"
                        f"{option_index}_"
                        f"{score}"
                    )
                )
            ]
        )

    keyboard.append(
        [
            InlineKeyboardButton(
                "🧠 خروج از آزمون",
                callback_data="psychology_socialwork"
            )
        ]
    )

    return text, InlineKeyboardMarkup(keyboard)


