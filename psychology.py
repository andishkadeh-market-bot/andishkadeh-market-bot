# =========================================================
# 🧠 منوی اصلی روانشناسی و مددکاری
# =========================================================

def psychology_menu():

    keyboard = []

    for chapter, name in PSYCHOLOGY_CHAPTER_NAMES.items():

        icon = PSYCHOLOGY_CHAPTER_ICONS.get(
            chapter,
            "🧠"
        )

        keyboard.append(
            [
                InlineKeyboardButton(
                    f"{icon} فصل {chapter} | {name}",
                    callback_data=(
                        f"psychology_chapter_{chapter}"
                    )
                )
            ]
        )

    keyboard.extend(
        [

            [
                InlineKeyboardButton(
                    "📝 آزمون جامع روانشناسی",
                    callback_data="psychology_full_exam"
                )
            ],

            [
                InlineKeyboardButton(
                    "🤝 آزمون جامع مددکاری",
                    callback_data="socialwork_full_exam"
                )
            ],

            [
                InlineKeyboardButton(
                    "🎯 مهارت‌های کاربردی",
                    callback_data="psychology_skills"
                )
            ],

            [
                InlineKeyboardButton(
                    "🏠 منوی اصلی",
                    callback_data="home"
                )
            ],

        ]
    )

    return InlineKeyboardMarkup(keyboard)


