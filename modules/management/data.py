def get_curriculum_statistics() -> dict[str, int]:
    """Return curriculum statistics."""

    chapters = len(
        MANAGEMENT_CURRICULUM
    )

    lessons = 0
    questions = 0

    for chapter_id, chapter_lessons in MANAGEMENT_LESSONS.items():

        if not isinstance(
            chapter_lessons,
            list,
        ):
            continue

        lessons += len(
            chapter_lessons
        )

        for lesson in chapter_lessons:

            if not isinstance(
                lesson,
                dict,
            ):
                continue

            lesson_id = lesson.get(
                "id"
            )

            if not lesson_id:
                continue

            questions += len(
                MANAGEMENT_QUIZ_QUESTIONS.get(
                    (
                        chapter_id,
                        lesson_id,
                    ),
                    [],
                )
            )

    return {
        "chapters": chapters,
        "lessons": lessons,
        "questions": questions,
    }


def data_health_check() -> bool:
    """Validate Management module data."""

    try:

        if not MODULE_ID:
            return False

        if not MODULE_TITLE:
            return False

        if not isinstance(
            MANAGEMENT_CURRICULUM,
            list,
        ):
            return False

        if len(
            MANAGEMENT_CURRICULUM
        ) != 12:
            return False

        chapter_ids: set[str] = set()

        for chapter in MANAGEMENT_CURRICULUM:

            if not isinstance(
                chapter,
                dict,
            ):
                return False

            chapter_id = chapter.get(
                "id"
            )

            title = chapter.get(
                "title"
            )

            description = chapter.get(
                "description"
            )

            if not chapter_id:
                return False

            if not title:
                return False

            if not description:
                return False

            if chapter_id in chapter_ids:
                return False

            chapter_ids.add(
                str(chapter_id)
            )

            if chapter_id not in MANAGEMENT_LESSONS:
                return False

            lessons = MANAGEMENT_LESSONS.get(
                chapter_id
            )

            if not isinstance(
                lessons,
                list,
            ):
                return False

            if len(lessons) < 1:
                return False

            lesson_ids: set[str] = set()

            for lesson in lessons:

                if not isinstance(
                    lesson,
                    dict,
                ):
                    return False

                lesson_id = lesson.get(
                    "id"
                )

                lesson_title = lesson.get(
                    "title"
                )

                content = lesson.get(
                    "content"
                )

                special_points = lesson.get(
                    "special_points"
                )

                exam_points = lesson.get(
                    "exam_points"
                )

                example = lesson.get(
                    "example"
                )

                if not lesson_id:
                    return False

                if lesson_id in lesson_ids:
                    return False

                lesson_ids.add(
                    str(lesson_id)
                )

                if not lesson_title:
                    return False

                if not content:
                    return False

                if not isinstance(
                    special_points,
                    list,
                ):
                    return False

                if not isinstance(
                    exam_points,
                    list,
                ):
                    return False

                if not example:
                    return False

                quiz_key = (
                    str(chapter_id),
                    str(lesson_id),
                )

                questions = MANAGEMENT_QUIZ_QUESTIONS.get(
                    quiz_key,
                    [],
                )

                if not isinstance(
                    questions,
                    list,
                ):
                    return False

                for question in questions:

                    if not isinstance(
                        question,
                        dict,
                    ):
                        return False

                    question_id = question.get(
                        "id"
                    )

                    question_text = question.get(
                        "question"
                    )

                    options = question.get(
                        "options"
                    )

                    correct_answer = question.get(
                        "correct_answer"
                    )

                    if not question_id:
                        return False

                    if not question_text:
                        return False

                    if not isinstance(
                        options,
                        list,
                    ):
                        return False

                    if len(options) < 2:
                        return False

                    if correct_answer not in options:
                        return False

        statistics = get_curriculum_statistics()

        if statistics["chapters"] != 12:
            return False

        if statistics["lessons"] < 1:
            return False

        if statistics["questions"] < 1:
            return False

        return True

    except Exception:
        return False


