# Basic API
# ==========================================================

def get_chapters() -> list[dict[str, Any]]:
    """Return all management chapters."""
    return list(MANAGEMENT_CURRICULUM)


def get_chapter(
    chapter_id: str,
) -> dict[str, Any] | None:
    """Return one chapter by ID."""

    for chapter in MANAGEMENT_CURRICULUM:
        if chapter.get("id") == chapter_id:
            return chapter

    return None


def get_lessons(
    chapter_id: str,
) -> list[dict[str, Any]]:
    """Return all lessons for a chapter."""

    return list(
        MANAGEMENT_LESSONS.get(
            chapter_id,
            [],
        )
    )


def get_lesson(
    chapter_id: str,
    lesson_id: str,
) -> dict[str, Any] | None:
    """Return one lesson."""

    for lesson in MANAGEMENT_LESSONS.get(
        chapter_id,
        [],
    ):
        if lesson.get("id") == lesson_id:
            return lesson

    return None


def get_quiz_questions(
    chapter_id: str,
    lesson_id: str,
) -> list[dict[str, Any]]:
    """Return quiz questions for a lesson."""

    return list(
        MANAGEMENT_QUIZ_QUESTIONS.get(
            (
                chapter_id,
                lesson_id,
            ),
            [],
        )
    )


