def search_lessons(
    keyword: str,
) -> list[dict[str, Any]]:
    """Search lessons by title or content."""

    if not keyword:
        return []

    keyword = keyword.strip().lower()

    if not keyword:
        return []

    results: list[dict[str, Any]] = []

    for chapter in MANAGEMENT_CURRICULUM:

        chapter_id = chapter.get(
            "id"
        )

        if not chapter_id:
            continue

        for lesson in get_lessons(
            str(chapter_id)
        ):

            title = str(
                lesson.get(
                    "title",
                    "",
                )
            ).lower()

            content = str(
                lesson.get(
                    "content",
                    "",
                )
            ).lower()

            if (
                keyword in title
                or keyword in content
            ):

                item = dict(
                    lesson
                )

                item.setdefault(
                    "chapter_id",
                    chapter_id,
                )

                results.append(
                    item
                )

    return results


