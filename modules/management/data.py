# ==========================================================
# Data Health Check
# ==========================================================

def data_health_check() -> bool:
    """
    Validate Management module data.

    This function intentionally validates the actual public API
    required by handlers.py.
    """

    try:

        if not MODULE_ID:
            return False

        if not MODULE_TITLE:
            return False

        if not MODULE_DESCRIPTION:
            return False

        if not isinstance(
            MANAGEMENT_CHAPTERS,
            list,
        ):
            return False

        if len(
            MANAGEMENT_CHAPTERS
        ) != 12:
            return False

        chapter_ids: set[str] = set()

        for chapter in MANAGEMENT_CHAPTERS:

            if not isinstance(
                chapter,
                dict,
            ):
                return False

            chapter_id = chapter.get(
                "id"
            )

            title = chapter.get(
                "title"
            )

            if not chapter_id:
                return False

            if not title:
                return False

            chapter_id = str(
                chapter_id
            )

            if chapter_id in chapter_ids:
                return False

            chapter_ids.add(
                chapter_id
            )

            if chapter_id not in MANAGEMENT_LESSONS:
                return False

            lessons = get_management_lessons(
                chapter_id
            )

            if not lessons:
                return False

            lesson_ids: set[str] = set()

            for lesson in lessons:

                lesson_id = lesson.get(
                    "id"
                )

                lesson_title = lesson.get(
                    "title"
                )

                content = lesson.get(
                    "content"
                )

                if not lesson_id:
                    return False

                if not lesson_title:
                    return False

                if not content:
                    return False

                if lesson_id in lesson_ids:
                    return False

                lesson_ids.add(
                    lesson_id
                )

                if "specialized_tips" not in lesson:
                    return False

                if "exam_tips" not in lesson:
                    return False

                if "examples" not in lesson:
                    return False

                if "review" not in lesson:
                    return False

        stats = get_curriculum_statistics()

        if stats["chapters"] != 12:
            return False

        if stats["lessons"] < 30:
            return False

        if stats["questions"] < 30:
            return False

        return True

    except Exception:
        return False


