# ==========================================================
# Health check
# ==========================================================

def management_data_health_check() -> bool:
    """
    Validate the basic structure of Management content.
    """

    try:
        if not MODULE_ID:
            return False

        if not MODULE_TITLE:
            return False

        if not MANAGEMENT_CHAPTERS:
            return False

        chapter_ids: set[str] = set()
        lesson_ids: set[str] = set()

        for chapter in MANAGEMENT_CHAPTERS:

            chapter_id = chapter.get("id")
            chapter_title = chapter.get("title")

            if not chapter_id:
                return False

            if not chapter_title:
                return False

            if chapter_id in chapter_ids:
                return False

            chapter_ids.add(
                chapter_id
            )

            lessons = chapter.get(
                "lessons",
                [],
            )

            if not isinstance(
                lessons,
                list,
            ):
                return False

            for lesson in lessons:

                lesson_id = lesson.get(
                    "id"
                )

                lesson_title = lesson.get(
                    "title"
                )

                if not lesson_id:
                    return False

                if not lesson_title:
                    return False

                if lesson_id in lesson_ids:
                    return False

                lesson_ids.add(
                    lesson_id
                )

                required_fields = (
                    "summary",
                    "content",
                    "specialized_tips",
                    "exam_tips",
                    "examples",
                    "review",
                )

                for field in required_fields:

                    if field not in lesson:
                        return False

        return True

    except Exception:
        return False


