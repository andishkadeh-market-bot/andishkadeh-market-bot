def get_all_lessons() -> list[dict[str, Any]]:
    """Return all lessons."""

    result: list[dict[str, Any]] = []

    for chapter in MANAGEMENT_CURRICULUM:

        chapter_id = chapter.get(
            "id"
        )

        if not chapter_id:
            continue

        for lesson in get_management_lessons(
            str(chapter_id)
        ):

            item = dict(lesson)

            item.setdefault(
                "chapter_id",
                chapter_id,
            )

            result.append(item)

    return result


