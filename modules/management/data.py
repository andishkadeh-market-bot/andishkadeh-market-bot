def get_chapters() -> list[dict[str, Any]]:
    """Return all Management chapters."""

    return list(MANAGEMENT_CURRICULUM)


def get_chapter(
    chapter_id: str,
) -> dict[str, Any] | None:
    """Return one chapter by ID."""

    for chapter in MANAGEMENT_CURRICULUM:
        if chapter.get("id") == chapter_id:
            return chapter

    return None


def get_lessons(
    chapter_id: str,
) -> list[dict[str, Any]]:
    """Return lessons for a chapter."""

    lessons = MANAGEMENT_LESSONS.get(
        chapter_id,
        [],
    )

    return list(lessons)


def get_lesson(
    chapter_id: str,
    lesson_id: str,
) -> dict[str, Any] | None:
    """Return one lesson."""

    for lesson in MANAGEMENT_LESSONS.get(
        chapter_id,
        [],
    ):
        if lesson.get("id") == lesson_id:
            return lesson

    return None


def get_quiz_questions(
    chapter_id: str,
    lesson_id: str,
) -> list[dict[str, Any]]:
    """Return quiz questions for a lesson."""

    questions = MANAGEMENT_QUIZ_QUESTIONS.get(
        (
            chapter_id,
            lesson_id,
        ),
        [],
    )

    return list(questions)


def get_curriculum_statistics() -> dict[str, int]:
    """Return curriculum statistics."""

    chapters = len(
        MANAGEMENT_CURRICULUM
    )

    lessons = 0
    questions = 0

    for chapter_id, chapter_lessons in MANAGEMENT_LESSONS.items():
        if not isinstance(
            chapter_lessons,
            list,
        ):
            continue

        lessons += len(
            chapter_lessons
        )

        for lesson in chapter_lessons:
            lesson_id = lesson.get("id")

            if not lesson_id:
                continue

            questions += len(
                MANAGEMENT_QUIZ_QUESTIONS.get(
                    (
                        chapter_id,
                        lesson_id,
                    ),
                    [],
                )
            )

    return {
        "chapters": chapters,
        "lessons": lessons,
        "questions": questions,
    }


def data_health_check() -> bool:
    """Validate Management module data."""

    try:
        if not MODULE_ID:
            return False

        if not MODULE_TITLE:
            return False

        if not isinstance(
            MANAGEMENT_CURRICULUM,
            list,
        ):
            return False

        if len(
            MANAGEMENT_CURRICULUM
        ) != 12:
            return False

        chapter_ids: set[str] = set()

        for chapter in MANAGEMENT_CURRICULUM:

            if not isinstance(
                chapter,
                dict,
            ):
                return False

            chapter_id = chapter.get(
                "id"
            )

            title = chapter.get(
                "title"
            )

            if not chapter_id or not title:
                return False

            if chapter_id in chapter_ids:
                return False

            chapter_ids.add(
                str(chapter_id)
            )

            if chapter_id not in MANAGEMENT_LESSONS:
                return False

            lessons = MANAGEMENT_LESSONS.get(
                chapter_id
            )

            if not isinstance(
                lessons,
                list,
            ):
                return False

            for lesson in lessons:

                if not isinstance(
                    lesson,
                    dict,
                ):
                    return False

                lesson_id = lesson.get(
                    "id"
                )

                lesson_title = lesson.get(
                    "title"
                )

                if not lesson_id:
                    return False

                if not lesson_title:
                    return False

                if "content" not in lesson:
                    return False

        statistics = (
            get_curriculum_statistics()
        )

        if statistics["chapters"] != 12:
            return False

        if statistics["lessons"] < 1:
            return False

        return True

    except Exception:
        return False


