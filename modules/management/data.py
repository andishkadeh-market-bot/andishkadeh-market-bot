def get_management_chapters() -> list[dict[str, Any]]:
    """
    Return all Management chapters.
    """
    return MANAGEMENT_CHAPTERS


def get_management_chapter(
    chapter_id: str,
) -> dict[str, Any] | None:
    """
    Return one Management chapter by ID.
    """

    for chapter in MANAGEMENT_CHAPTERS:
        if chapter["id"] == chapter_id:
            return chapter

    return None


def get_management_lessons(
    chapter_id: str,
) -> list[dict[str, Any]]:
    """
    Return lessons belonging to a chapter.
    """

    chapter = get_management_chapter(
        chapter_id
    )

    if chapter is None:
        return []

    return chapter.get(
        "lessons",
        [],
    )


def get_management_lesson(
    chapter_id: str,
    lesson_id: str,
) -> dict[str, Any] | None:
    """
    Return one lesson by chapter and lesson ID.
    """

    lessons = get_management_lessons(
        chapter_id
    )

    for lesson in lessons:
        if lesson["id"] == lesson_id:
            return lesson

    return None


def get_all_management_lessons() -> list[dict[str, Any]]:
    """
    Return all Management lessons.
    """

    lessons: list[dict[str, Any]] = []

    for chapter in MANAGEMENT_CHAPTERS:
        lessons.extend(
            chapter.get(
                "lessons",
                [],
            )
        )

    return lessons


def get_management_statistics() -> dict[str, int]:
    """
    Return basic content statistics.
    """

    chapters = len(
        MANAGEMENT_CHAPTERS
    )

    lessons = len(
        get_all_management_lessons()
    )

    return {
        "chapters": chapters,
        "lessons": lessons,
    }


