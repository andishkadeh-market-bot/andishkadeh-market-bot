def _normalize_lesson(
    lesson: dict[str, Any],
) -> dict[str, Any]:
    """
    Normalize lesson data so both old and new handlers
    can consume it.
    """

    item = dict(lesson)

    # Old field names
    if "special_points" not in item:
        item["special_points"] = list(
            item.get("specialized_tips", [])
        )

    if "exam_points" not in item:
        item["exam_points"] = list(
            item.get("exam_tips", [])
        )

    if "example" not in item:
        examples = item.get(
            "examples",
            [],
        )

        if isinstance(
            examples,
            list,
        ):
            item["example"] = (
                "\n".join(
                    str(x)
                    for x in examples
                )
            )
        else:
            item["example"] = str(
                examples
            )

    # New field names
    if "specialized_tips" not in item:
        item["specialized_tips"] = list(
            item.get("special_points", [])
        )

    if "exam_tips" not in item:
        item["exam_tips"] = list(
            item.get("exam_points", [])
        )

    if "examples" not in item:
        example = item.get(
            "example",
            "",
        )

        item["examples"] = (
            [example]
            if example
            else []
        )

    if "review" not in item:
        item["review"] = []

    return item


def get_management_lessons(
    chapter_id: str,
) -> list[dict[str, Any]]:
    """Return normalized lessons for a chapter."""

    lessons = MANAGEMENT_LESSONS.get(
        chapter_id,
        [],
    )

    return [
        _normalize_lesson(lesson)
        for lesson in lessons
    ]


def get_management_lesson(
    chapter_id: str,
    lesson_id: str,
) -> dict[str, Any] | None:
    """Return one normalized Management lesson."""

    for lesson in MANAGEMENT_LESSONS.get(
        chapter_id,
        [],
    ):

        current_id = lesson.get(
            "id",
            lesson.get(
                "lesson_id",
            ),
        )

        if current_id == lesson_id:
            return _normalize_lesson(
                lesson
            )

    return None


