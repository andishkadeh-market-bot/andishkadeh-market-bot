# ==========================================================
# Quiz Helpers
# ==========================================================

def question(
    qid: str,
    text: str,
    options: list[dict[str, Any]],
    answer: str,
    explanation: str,
) -> dict[str, Any]:
    """Create a standard psychology/social-work quiz question."""

    return {
        "id": qid,
        "question": text,
        "options": options,
        "answer": answer,
        "correct_answer": answer,
        "explanation": explanation,
    }


def options(
    a: str,
    b: str,
    c: str,
    d: str,
) -> list[dict[str, Any]]:
    """Create four standard answer options."""

    return [
        {"id": "A", "text": a},
        {"id": "B", "text": b},
        {"id": "C", "text": c},
        {"id": "D", "text": d},
    ]


