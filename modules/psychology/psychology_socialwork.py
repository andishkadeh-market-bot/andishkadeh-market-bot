def get_chapters() -> list[dict[str, Any]]:
    """Return all psychology/social-work chapters."""
    return CHAPTERS


def get_chapter(
    chapter_id: str,
) -> dict[str, Any] | None:
    """Return one chapter by ID."""

    for chapter in CHAPTERS:
        if chapter.get("id") == chapter_id:
            return chapter

    return None


def get_lessons(
    chapter_id: str,
) -> list[dict[str, Any]]:
    """Return lessons belonging to a chapter."""

    chapter = get_chapter(chapter_id)

    if chapter is None:
        return []

    lessons = chapter.get("lessons", [])

    if not isinstance(lessons, list):
        return []

    return lessons


def get_lesson(
    chapter_id: str,
    lesson_id: str,
) -> dict[str, Any] | None:
    """Return one lesson."""

    for lesson in get_lessons(chapter_id):
        if lesson.get("id") == lesson_id:
            return lesson

    return None


def get_questions(
    chapter_id: str,
    lesson_id: str | None = None,
) -> list[dict[str, Any]]:
    """
    Return questions for a chapter.

    If lesson_id is provided, only that lesson's questions
    are returned.
    """

    lessons = get_lessons(chapter_id)

    result: list[dict[str, Any]] = []

    for lesson in lessons:

        if lesson_id is not None:
            if lesson.get("id") != lesson_id:
                continue

        questions = lesson.get("questions", [])

        if isinstance(questions, list):
            result.extend(
                q
                for q in questions
                if isinstance(q, dict)
            )

    return result


def get_all_questions() -> list[dict[str, Any]]:
    """Return all psychology/social-work questions."""

    result: list[dict[str, Any]] = []

    for chapter in CHAPTERS:

        chapter_id = chapter.get("id")

        if not chapter_id:
            continue

        result.extend(
            get_questions(
                str(chapter_id)
            )
        )

    return result


def get_module_info() -> dict[str, Any]:
    """Return module metadata."""

    statistics = get_curriculum_statistics()

    return {
        "id": MODULE_ID,
        "title": MODULE_TITLE,
        "description": MODULE_DESCRIPTION,
        "version": MODULE_VERSION,
        "chapters": statistics["chapters"],
        "lessons": statistics["lessons"],
        "questions": statistics["questions"],
    }


def get_curriculum_statistics() -> dict[str, int]:
    """Return curriculum statistics."""

    chapters_count = len(CHAPTERS)
    lessons_count = 0
    questions_count = 0

    for chapter in CHAPTERS:

        lessons = chapter.get(
            "lessons",
            [],
        )

        if not isinstance(
            lessons,
            list,
        ):
            continue

        lessons_count += len(lessons)

        for lesson in lessons:

            questions = lesson.get(
                "questions",
                [],
            )

            if isinstance(
                questions,
                list,
            ):
                questions_count += len(questions)

    return {
        "chapters": chapters_count,
        "lessons": lessons_count,
        "questions": questions_count,
    }


# ==========================================================
# Data Health Check
# ==========================================================

def data_health_check() -> bool:
    """
    Validate the complete psychology/social-work curriculum.
    """

    try:

        if not MODULE_ID:
            return False

        if not MODULE_TITLE:
            return False

        if not isinstance(
            CHAPTERS,
            list,
        ):
            return False

        if len(CHAPTERS) != 12:
            return False

        chapter_ids: set[str] = set()

        for chapter in CHAPTERS:

            if not isinstance(
                chapter,
                dict,
            ):
                return False

            chapter_id = chapter.get(
                "id"
            )

            chapter_title = chapter.get(
                "title"
            )

            lessons = chapter.get(
                "lessons"
            )

            if not chapter_id:
                return False

            if not chapter_title:
                return False

            chapter_id = str(
                chapter_id
            )

            if chapter_id in chapter_ids:
                return False

            chapter_ids.add(
                chapter_id
            )

            if not isinstance(
                lessons,
                list,
            ):
                return False

            if len(lessons) < 1:
                return False

            lesson_ids: set[str] = set()

            for lesson in lessons:

                if not isinstance(
                    lesson,
                    dict,
                ):
                    return False

                lesson_id = lesson.get(
                    "id"
                )

                lesson_title = lesson.get(
                    "title"
                )

                content = lesson.get(
                    "content"
                )

                if not lesson_id:
                    return False

                if not lesson_title:
                    return False

                if not isinstance(
                    content,
                    str,
                ):
                    return False

                if not content.strip():
                    return False

                lesson_id = str(
                    lesson_id
                )

                if lesson_id in lesson_ids:
                    return False

                lesson_ids.add(
                    lesson_id
                )

                specialized_notes = lesson.get(
                    "specialized_notes",
                    [],
                )

                exam_notes = lesson.get(
                    "exam_notes",
                    [],
                )

                questions = lesson.get(
                    "questions",
                    [],
                )

                if not isinstance(
                    specialized_notes,
                    list,
                ):
                    return False

                if not isinstance(
                    exam_notes,
                    list,
                ):
                    return False

                if not isinstance(
                    questions,
                    list,
                ):
                    return False

                question_ids: set[str] = set()

                for quiz in questions:

                    if not isinstance(
                        quiz,
                        dict,
                    ):
                        return False

                    required_keys = {
                        "id",
                        "question",
                        "options",
                        "answer",
                        "correct_answer",
                        "explanation",
                    }

                    if not required_keys.issubset(
                        quiz.keys()
                    ):
                        return False

                    quiz_id = quiz.get(
                        "id"
                    )

                    if not quiz_id:
                        return False

                    quiz_id = str(
                        quiz_id
                    )

                    if quiz_id in question_ids:
                        return False

                    question_ids.add(
                        quiz_id
                    )

                    if not quiz.get(
                        "question"
                    ):
                        return False

                    quiz_options = quiz.get(
                        "options"
                    )

                    if not isinstance(
                        quiz_options,
                        list,
                    ):
                        return False

                    if len(
                        quiz_options
                    ) != 4:
                        return False

                    option_ids: set[str] = set()

                    for option in quiz_options:

                        if not isinstance(
                            option,
                            dict,
                        ):
                            return False

                        option_id = option.get(
                            "id"
                        )

                        option_text = option.get(
                            "text"
                        )

                        if not option_id:
                            return False

                        if not option_text:
                            return False

                        option_id = str(
                            option_id
                        )

                        if option_id in option_ids:
                            return False

                        option_ids.add(
                            option_id
                        )

                    answer = str(
                        quiz.get(
                            "answer"
                        )
                    )

                    if answer not in option_ids:
                        return False

                    correct_answer = str(
                        quiz.get(
                            "correct_answer"
                        )
                    )

                    if correct_answer != answer:
                        return False

                    if not quiz.get(
                        "explanation"
                    ):
                        return False

        statistics = get_curriculum_statistics()

        if statistics["chapters"] != 12:
            return False

        if statistics["lessons"] < 12:
            return False

        if statistics["questions"] < 12:
            return False

        return True

    except Exception:
        return False


