def get_lesson_content(lesson_id: str) -> dict | None:
    """
    Return educational content for a specific Finance lesson.
    """
    content = FINANCE_CONTENT.get(lesson_id)
    if content is None:
        return None
    return {
        "lesson_id": content["lesson_id"],
        "title": content["title"],
        "lesson_text": content["lesson_text"],
        "subtopics": list(content["subtopics"]),
        "detailed_content": content["detailed_content"],
        "specialized_points": list(content["specialized_points"]),
        "exam_points": list(content["exam_points"]),
        "practical_example": content["practical_example"],
        "review": content["review"],
    }
def get_all_lesson_content() -> list:
    """
    Return educational content for all Finance lessons.
    """
    return [
        get_lesson_content(lesson_id)
        for lesson_id in FINANCE_CONTENT
    ]
def get_content_statistics() -> dict:
    """
    Return statistics for Finance educational content.
    """
    return {
        "module_id": MODULE_ID,
        "lessons_with_content": len(FINANCE_CONTENT),
        "expected_lessons": 48,
        "complete": len(FINANCE_CONTENT) == 48,
    }
def content_health_check() -> bool:
    """
    Validate Finance educational content.
    """
    expected_ids = {
        f"finance_l{number}"
        for number in range(1, 49)
    }
    actual_ids = set(FINANCE_CONTENT.keys())
    if actual_ids != expected_ids:
        return False
    required_fields = {
        "lesson_id",
        "title",
        "lesson_text",
        "subtopics",
        "detailed_content",
        "specialized_points",
        "exam_points",
        "practical_example",
        "review",
    }
    for lesson_id, content in FINANCE_CONTENT.items():
        if not isinstance(content, dict):
            return False
        if not required_fields.issubset(content.keys()):
            return False
        if content.get("lesson_id") != lesson_id:
            return False
        if not content.get("title"):
            return False
        if not content.get("lesson_text"):
            return False
        if not content.get("detailed_content"):
            return False
        if not content.get("review"):
            return False
        if not isinstance(content.get("subtopics"), list):
            return False
        if not isinstance(content.get("specialized_points"), list):
            return False
        if not isinstance(content.get("exam_points"), list):
            return False
    return True
