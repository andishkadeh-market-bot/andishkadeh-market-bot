def get_chapters() -> list[dict[str, Any]]:
    return CHAPTERS


def get_chapter(
    chapter_id: str,
) -> dict[str, Any] | None:

    normalized = str(
        chapter_id or ""
    ).strip()

    for chapter in CHAPTERS:
        if chapter.get("id") == normalized:
            return chapter

    return None


def get_lessons(
    chapter_id: str,
) -> list[dict[str, Any]]:

    chapter = get_chapter(
        chapter_id
    )

    if chapter is None:
        return []

    lessons = chapter.get(
        "lessons",
        []
    )

    return lessons if isinstance(
        lessons,
        list,
    ) else []


def get_lesson(
    chapter_id: str,
    lesson_id: str,
) -> dict[str, Any] | None:

    normalized_chapter = str(
        chapter_id or ""
    ).strip()

    normalized_lesson = str(
        lesson_id or ""
    ).strip()

    for lesson in get_lessons(
        normalized_chapter
    ):
        if lesson.get(
            "id"
        ) == normalized_lesson:
            return lesson

    return None


def get_quiz_questions(
    chapter_id: str,
    lesson_id: str,
) -> list[dict[str, Any]]:

    lesson = get_lesson(
        chapter_id,
        lesson_id,
    )

    if lesson is None:
        return []

    lesson_id_normalized = str(
        lesson.get("id")
        or ""
    ).strip()

    return list(
        QUIZ_QUESTIONS.get(
            lesson_id_normalized,
            [],
        )
    )


def get_all_quiz_questions() -> list[dict[str, Any]]:

    questions: list[
        dict[str, Any]
    ] = []

    for lesson_questions in (
        QUIZ_QUESTIONS.values()
    ):
        questions.extend(
            lesson_questions
        )

    return questions


def get_curriculum_statistics() -> dict[str, int]:

    chapters = len(
        CHAPTERS
    )

    lessons = sum(
        len(
            chapter.get(
                "lessons",
                [],
            )
        )
        for chapter in CHAPTERS
    )

    quiz_questions = len(
        get_all_quiz_questions()
    )

    return {
        "modules": 1,
        "chapters": chapters,
        "lessons": lessons,
        "quiz_questions": quiz_questions,
    }


