def get_chapters() -> list[dict[str, Any]]:
    """Return all Marketing chapters."""
    return list(MARKETING_CURRICULUM)


def get_chapter(
    chapter_id: str,
) -> dict[str, Any] | None:
    """Return one Marketing chapter."""
    if chapter_id is None:
        return None

    normalized_id = str(
        chapter_id
    ).strip()

    for chapter in MARKETING_CURRICULUM:
        if chapter.get("id") == normalized_id:
            return dict(chapter)

    return None


def get_lessons(
    chapter_id: str,
) -> list[dict[str, Any]]:
    """Return lessons for a chapter."""
    if chapter_id is None:
        return []

    normalized_id = str(
        chapter_id
    ).strip()

    return [
        dict(lesson)
        for lesson in MARKETING_LESSONS.get(
            normalized_id,
            [],
        )
    ]


def get_lesson(
    chapter_id: str,
    lesson_id: str,
) -> dict[str, Any] | None:
    """Return one lesson."""
    if (
        chapter_id is None
        or lesson_id is None
    ):
        return None

    normalized_chapter_id = str(
        chapter_id
    ).strip()

    normalized_lesson_id = str(
        lesson_id
    ).strip()

    for lesson in MARKETING_LESSONS.get(
        normalized_chapter_id,
        [],
    ):
        if lesson.get("id") == normalized_lesson_id:
            return dict(lesson)

    return None


def get_quiz_questions(
    chapter_id: str,
    lesson_id: str,
) -> list[dict[str, Any]]:
    """Return quiz questions for a lesson."""
    if (
        chapter_id is None
        or lesson_id is None
    ):
        return []

    questions = MARKETING_QUIZ_QUESTIONS.get(
        (
            str(chapter_id).strip(),
            str(lesson_id).strip(),
        ),
        [],
    )

    return [
        dict(question)
        for question in questions
    ]


