def get_data_quality_report() -> dict[str, Any]:
    """Return detailed data quality information."""

    errors: list[str] = []
    warnings: list[str] = []

    seen_chapters: set[str] = set()

    for index, chapter in enumerate(
        MARKETING_CURRICULUM,
        start=1,
    ):

        chapter_id = str(
            chapter.get(
                "id",
                "",
            )
        ).strip()

        if not chapter_id:
            errors.append(
                f"Chapter #{index} has no ID."
            )
            continue

        if chapter_id in seen_chapters:
            errors.append(
                f"Duplicate chapter ID: {chapter_id}"
            )

        seen_chapters.add(
            chapter_id
        )

        lessons = MARKETING_LESSONS.get(
            chapter_id,
            [],
        )

        if not lessons:
            warnings.append(
                f"Chapter '{chapter_id}' has no lessons."
            )

        for lesson in lessons:

            lesson_id = str(
                lesson.get(
                    "id",
                    "",
                )
            ).strip()

            if not lesson_id:
                errors.append(
                    f"Chapter '{chapter_id}' contains lesson without ID."
                )

            if not lesson.get(
                "title"
            ):
                warnings.append(
                    f"Lesson '{lesson_id}' has no title."
                )

            if not lesson.get(
                "content"
            ):
                errors.append(
                    f"Lesson '{lesson_id}' has no content."
                )

            quiz_count = len(
                MARKETING_QUIZ_QUESTIONS.get(
                    (
                        chapter_id,
                        lesson_id,
                    ),
                    [],
                )
            )

            if quiz_count == 0:
                warnings.append(
                    f"Lesson '{lesson_id}' has no quiz questions."
                )

    stats = get_curriculum_statistics()

    return {
        "valid": not errors,
        "errors": errors,
        "warnings": warnings,
        "statistics": stats,
    }


