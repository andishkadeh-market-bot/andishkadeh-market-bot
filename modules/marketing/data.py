def get_curriculum_statistics() -> dict[str, int]:
    """Return curriculum statistics."""

    chapters = len(
        MARKETING_CURRICULUM
    )

    lessons = 0
    questions = 0

    for chapter in MARKETING_CURRICULUM:

        chapter_id = chapter.get(
            "id"
        )

        if not chapter_id:
            continue

        chapter_lessons = MARKETING_LESSONS.get(
            chapter_id,
            [],
        )

        lessons += len(
            chapter_lessons
        )

        for lesson in chapter_lessons:

            lesson_id = lesson.get(
                "id"
            )

            if not lesson_id:
                continue

            questions += len(
                MARKETING_QUIZ_QUESTIONS.get(
                    (
                        chapter_id,
                        lesson_id,
                    ),
                    [],
                )
            )

    return {
        "chapters": chapters,
        "lessons": lessons,
        "questions": questions,
    }


