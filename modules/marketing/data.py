def data_health_check() -> bool:
    """Validate Marketing module data."""

    try:

        if not MODULE_ID:
            return False

        if not MODULE_TITLE:
            return False

        if not isinstance(
            MARKETING_CURRICULUM,
            list,
        ):
            return False

        if len(
            MARKETING_CURRICULUM
        ) != 12:
            return False

        chapter_ids: set[str] = set()

        for chapter in MARKETING_CURRICULUM:

            if not isinstance(
                chapter,
                dict,
            ):
                return False

            chapter_id = chapter.get(
                "id"
            )

            title = chapter.get(
                "title"
            )

            if not chapter_id:
                return False

            if not title:
                return False

            if chapter_id in chapter_ids:
                return False

            chapter_ids.add(
                str(chapter_id)
            )

            if chapter_id not in MARKETING_LESSONS:
                return False

            lessons = MARKETING_LESSONS.get(
                chapter_id,
                [],
            )

            if not isinstance(
                lessons,
                list,
            ):
                return False

            lesson_ids: set[str] = set()

            for lesson in lessons:

                if not isinstance(
                    lesson,
                    dict,
                ):
                    return False

                lesson_id = lesson.get(
                    "id"
                )

                lesson_title = lesson.get(
                    "title"
                )

                content = lesson.get(
                    "content"
                )

                if not lesson_id:
                    return False

                if lesson_id in lesson_ids:
                    return False

                lesson_ids.add(
                    str(lesson_id)
                )

                if not lesson_title:
                    return False

                if not isinstance(
                    content,
                    str,
                ):
                    return False

                if not content.strip():
                    return False

                if "special_points" not in lesson:
                    return False

                if "exam_points" not in lesson:
                    return False

                if "example" not in lesson:
                    return False

        stats = get_curriculum_statistics()

        if stats["chapters"] != 12:
            return False

        if stats["lessons"] < 1:
            return False

        if stats["questions"] < 1:
            return False

        return True

    except Exception:
        return False


def health_check() -> bool:
    """Generic health-check alias."""
    return data_health_check()


