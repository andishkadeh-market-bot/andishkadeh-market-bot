def search_lessons(
    keyword: str,
) -> list[dict[str, Any]]:
    """Search lessons by title and content."""
    if keyword is None:
        return []
    normalized_keyword = str(
        keyword
    ).strip().casefold()
    if not normalized_keyword:
        return []
    results: list[
        dict[str, Any]
    ] = []
    for chapter in INTERNATIONAL_TRADE_CURRICULUM:
        chapter_id = str(
            chapter.get("id", "")
        ).strip()
        for lesson in get_lessons(
            chapter_id
        ):
            lesson_id = str(
                lesson.get("id", "")
            ).strip()
            title = str(
                lesson.get(
                    "title",
                    "",
                )
            )
            content = str(
                lesson.get(
                    "content",
                    "",
                )
            )
            special_points = " ".join(
                str(item)
                for item in lesson.get(
                    "special_points",
                    [],
                )
            )
            exam_points = " ".join(
                str(item)
                for item in lesson.get(
                    "exam_points",
                    [],
                )
            )
            searchable = (
                f"{title}\n"
                f"{content}\n"
                f"{special_points}\n"
                f"{exam_points}"
            ).casefold()
            if normalized_keyword in searchable:
                results.append(
                    {
                        "module_id": MODULE_ID,
                        "chapter_id": chapter_id,
                        "lesson_id": lesson_id,
                        "title": title,
                    }
                )
    return results
