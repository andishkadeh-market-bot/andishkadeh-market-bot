# Data Health Check
# ==========================================================
def data_health_check() -> bool:
    """Validate module data integrity."""
    try:
        if not MODULE_ID:
            return False
        if not MODULE_TITLE:
            return False
        if not isinstance(
            INTERNATIONAL_TRADE_CURRICULUM,
            list,
        ):
            return False
        if len(
            INTERNATIONAL_TRADE_CURRICULUM
        ) != 15:
            return False
        chapter_ids: set[str] = set()
        for chapter in INTERNATIONAL_TRADE_CURRICULUM:
            if not isinstance(
                chapter,
                dict,
            ):
                return False
            chapter_id = str(
                chapter.get("id", "")
            ).strip()
            chapter_title = str(
                chapter.get("title", "")
            ).strip()
            if not chapter_id:
                return False
            if not chapter_title:
                return False
            if chapter_id in chapter_ids:
                return False
            chapter_ids.add(
                chapter_id
            )
            if chapter_id not in INTERNATIONAL_TRADE_LESSONS:
                return False
            lessons = INTERNATIONAL_TRADE_LESSONS.get(
                chapter_id,
                [],
            )
            if not isinstance(
                lessons,
                list,
            ):
                return False
            lesson_ids: set[str] = set()
            for lesson in lessons:
                if not isinstance(
                    lesson,
                    dict,
                ):
                    return False
                lesson_id = str(
                    lesson.get("id", "")
                ).strip()
                title = str(
                    lesson.get("title", "")
                ).strip()
                content = lesson.get(
                    "content"
                )
                if not lesson_id:
                    return False
                if not title:
                    return False
                if lesson_id in lesson_ids:
                    return False
                lesson_ids.add(
                    lesson_id
                )
                if not isinstance(
                    content,
                    str,
                ):
                    return False
                if not content.strip():
                    return False
                questions = (
                    INTERNATIONAL_TRADE_QUIZ_QUESTIONS.get(
                        (
                            chapter_id,
                            lesson_id,
                        ),
                        [],
                    )
                )
                if not isinstance(
                    questions,
                    list,
                ):
                    return False
                for question in questions:
                    if not isinstance(
                        question,
                        dict,
                    ):
                        return False
                    if not question.get(
                        "id"
                    ):
                        return False
                    if not question.get(
                        "question"
                    ):
                        return False
                    options = question.get(
                        "options"
                    )
                    if not isinstance(
                        options,
                        list,
                    ):
                        return False
                    if len(options) != 4:
                        return False
                    correct_answer = question.get(
                        "correct_answer"
                    )
                    if correct_answer not in options:
                        return False
        statistics = (
            get_curriculum_statistics()
        )
        if statistics["chapters"] != 15:
            return False
        if statistics["lessons"] < 1:
            return False
        if statistics["questions"] < 1:
            return False
        return True
    except Exception:
        return False
