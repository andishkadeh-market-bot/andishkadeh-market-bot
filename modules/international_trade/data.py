def get_all_lessons() -> list[dict[str, Any]]:
    """Return all lessons."""
    result: list[dict[str, Any]] = []
    for chapter in INTERNATIONAL_TRADE_CURRICULUM:
        chapter_id = chapter.get("id")
        if not chapter_id:
            continue
        for lesson in get_lessons(
            str(chapter_id)
        ):
            item = dict(lesson)
            item.setdefault(
                "chapter_id",
                chapter_id,
            )
            result.append(item)
    return result
def get_all_questions() -> list[dict[str, Any]]:
    """Return all quiz questions."""
    result: list[dict[str, Any]] = []
    for key, questions in INTERNATIONAL_TRADE_QUIZ_QUESTIONS.items():
        chapter_id, lesson_id = key
        for question in questions:
            item = dict(question)
            item.setdefault(
                "chapter_id",
                chapter_id,
            )
            item.setdefault(
                "lesson_id",
                lesson_id,
            )
            result.append(item)
    return result
