# Search
# ==========================================================

def search_lessons(
    keyword: str,
) -> list[dict[str, Any]]:
    """Search lessons by title and content."""

    normalized_keyword = str(
        keyword or ""
    ).strip().casefold()

    if not normalized_keyword:
        return []

    results: list[
        dict[str, Any]
    ] = []

    for chapter in INTERNATIONAL_TRADE_CURRICULUM:

        chapter_id = str(
            chapter.get("id") or ""
        ).strip()

        for lesson in get_lessons(
            chapter_id
        ):

            title = str(
                lesson.get(
                    "title",
                    "",
                )
            )

            content = str(
                lesson.get(
                    "content",
                    "",
                )
            )

            terms = lesson.get(
                "terms",
                [],
            )

            terms_text = " ".join(
                str(term)
                for term in terms
            )

            searchable_text = (
                f"{title}\n"
                f"{content}\n"
                f"{terms_text}"
            ).casefold()

            if normalized_keyword in searchable_text:

                results.append(
                    {
                        "module_id": MODULE_ID,
                        "chapter_id": chapter_id,
                        "lesson_id": lesson.get("id"),
                        "title": title,
                    }
                )

    return results


# ==========================================================
# Health Check
# ==========================================================

def data_health_check() -> bool:
    """
    Validate International Trade module data.

    The validation intentionally checks both curriculum
    structure and lesson/quiz integrity.
    """

    try:

        if not MODULE_ID:
            return False

        if not MODULE_TITLE:
            return False

        if not isinstance(
            INTERNATIONAL_TRADE_CURRICULUM,
            list,
        ):
            return False

        if len(
            INTERNATIONAL_TRADE_CURRICULUM
        ) != 12:
            return False

        chapter_ids: set[str] = set()

        for chapter in INTERNATIONAL_TRADE_CURRICULUM:

            if not isinstance(
                chapter,
                dict,
            ):
                return False

            chapter_id = str(
                chapter.get("id") or ""
            ).strip()

            title = str(
                chapter.get("title") or ""
            ).strip()

            if not chapter_id:
                return False

            if not title:
                return False

            if chapter_id in chapter_ids:
                return False

            chapter_ids.add(
                chapter_id
            )

            if chapter_id not in INTERNATIONAL_TRADE_LESSONS:
                return False

            lessons = INTERNATIONAL_TRADE_LESSONS.get(
                chapter_id,
                [],
            )

            if not isinstance(
                lessons,
                list,
            ):
                return False

            lesson_ids: set[str] = set()

            for lesson in lessons:

                if not isinstance(
                    lesson,
                    dict,
                ):
                    return False

                lesson_id = str(
                    lesson.get("id") or ""
                ).strip()

                lesson_title = str(
                    lesson.get("title") or ""
                ).strip()

                content = lesson.get(
                    "content"
                )

                if not lesson_id:
                    return False

                if not lesson_title:
                    return False

                if lesson_id in lesson_ids:
                    return False

                lesson_ids.add(
                    lesson_id
                )

                if not isinstance(
                    content,
                    str,
                ):
                    return False

                if not content.strip():
                    return False

                questions = INTERNATIONAL_TRADE_QUIZ_QUESTIONS.get(
                    (
                        chapter_id,
                        lesson_id,
                    ),
                    [],
                )

                if not isinstance(
                    questions,
                    list,
                ):
                    return False

                for question in questions:

                    if not isinstance(
                        question,
                        dict,
                    ):
                        return False

                    if not question.get("id"):
                        return False

                    if not question.get("question"):
                        return False

                    options = question.get(
                        "options",
                        [],
                    )

                    if not isinstance(
                        options,
                        list,
                    ):
                        return False

                    if len(options) < 2:
                        return False

                    if not question.get(
                        "correct_answer"
                    ):
                        return False

        statistics = get_curriculum_statistics()

        if statistics["chapters"] != 12:
            return False

        if statistics["lessons"] < 1:
            return False

        if statistics["questions"] < 1:
            return False

        return True

    except Exception:
        return False


