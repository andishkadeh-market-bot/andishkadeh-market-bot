def get_all_lessons() -> list[dict[str, Any]]:
    """Return all lessons."""
    result: list[dict[str, Any]] = []
    for chapter in INTERNATIONAL_TRADE_CURRICULUM:
        chapter_id = str(
            chapter.get("id", "")
        ).strip()
        if not chapter_id:
            continue
        for lesson in get_lessons(
            chapter_id
        ):
            item = dict(lesson)
            item.setdefault(
                "chapter_id",
                chapter_id,
            )
            result.append(
                item
            )
    return result
def get_all_questions() -> list[dict[str, Any]]:
    """Return all quiz questions."""
    result: list[dict[str, Any]] = []
    for (
        chapter_id,
        lesson_id,
    ), questions in INTERNATIONAL_TRADE_QUIZ_QUESTIONS.items():
        for question in questions:
            item = dict(question)
            item.setdefault(
                "chapter_id",
                chapter_id,
            )
            item.setdefault(
                "lesson_id",
                lesson_id,
            )
            result.append(
                item
            )
    return result
