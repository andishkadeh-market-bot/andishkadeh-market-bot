def get_chapters() -> list[dict[str, Any]]:
    """Return all International Trade chapters."""
    return [
        dict(chapter)
        for chapter in INTERNATIONAL_TRADE_CURRICULUM
    ]


def get_chapter(
    chapter_id: str,
) -> dict[str, Any] | None:
    """Return one chapter by ID."""

    normalized = str(
        chapter_id
    ).strip()

    if not normalized:
        return None

    for chapter in INTERNATIONAL_TRADE_CURRICULUM:
        if chapter.get("id") == normalized:
            return dict(chapter)

    return None


def get_lessons(
    chapter_id: str,
) -> list[dict[str, Any]]:
    """Return all lessons for a chapter."""

    normalized = str(
        chapter_id
    ).strip()

    if not normalized:
        return []

    return [
        dict(lesson)
        for lesson in INTERNATIONAL_TRADE_LESSONS.get(
            normalized,
            [],
        )
    ]


def get_lesson(
    chapter_id: str,
    lesson_id: str,
) -> dict[str, Any] | None:
    """Return one lesson."""

    chapter = str(
        chapter_id
    ).strip()

    lesson_key = str(
        lesson_id
    ).strip()

    if not chapter or not lesson_key:
        return None

    for lesson in INTERNATIONAL_TRADE_LESSONS.get(
        chapter,
        [],
    ):
        if lesson.get("id") == lesson_key:
            return dict(lesson)

    return None


def get_quiz_questions(
    chapter_id: str,
    lesson_id: str,
) -> list[dict[str, Any]]:
    """Return quiz questions for a lesson."""

    chapter = str(
        chapter_id
    ).strip()

    lesson_key = str(
        lesson_id
    ).strip()

    if not chapter or not lesson_key:
        return []

    return [
        dict(question)
        for question in INTERNATIONAL_TRADE_QUIZ_QUESTIONS.get(
            (
                chapter,
                lesson_key,
            ),
            [],
        )
    ]


