def search_lessons(
    query: str,
) -> list[dict[str, Any]]:
    """
    Search lessons by title/content/keywords.
    """
    query = str(
        query or ""
    ).strip().lower()
    if not query:
        return []
    results: list[dict[str, Any]] = []
    for lesson in get_all_lessons():
        searchable = " ".join(
            [
                str(
                    lesson.get(
                        "title",
                        "",
                    )
                ),
                str(
                    lesson.get(
                        "content",
                        "",
                    )
                ),
                " ".join(
                    map(
                        str,
                        lesson.get(
                            "special_points",
                            [],
                        ),
                    )
                ),
                " ".join(
                    map(
                        str,
                        lesson.get(
                            "exam_points",
                            [],
                        ),
                    )
                ),
            ]
        ).lower()
        if query in searchable:
            results.append(
                lesson
            )
    return results
