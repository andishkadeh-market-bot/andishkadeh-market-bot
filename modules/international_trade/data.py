def get_chapters() -> list[dict[str, Any]]:
    """Return all chapters."""
    return [
        dict(chapter)
        for chapter in INTERNATIONAL_TRADE_CURRICULUM
    ]
def get_chapter(
    chapter_id: str,
) -> dict[str, Any] | None:
    """Return one chapter by ID."""
    normalized_id = str(
        chapter_id
    ).strip()
    for chapter in INTERNATIONAL_TRADE_CURRICULUM:
        if str(
            chapter.get("id", "")
        ).strip() == normalized_id:
            return dict(chapter)
    return None
def get_lessons(
    chapter_id: str,
) -> list[dict[str, Any]]:
    """Return lessons for a chapter."""
    normalized_id = str(
        chapter_id
    ).strip()
    return [
        dict(lesson)
        for lesson in INTERNATIONAL_TRADE_LESSONS.get(
            normalized_id,
            [],
        )
    ]
def get_lesson(
    chapter_id: str,
    lesson_id: str,
) -> dict[str, Any] | None:
    """Return one lesson."""
    normalized_chapter = str(
        chapter_id
    ).strip()
    normalized_lesson = str(
        lesson_id
    ).strip()
    for lesson in INTERNATIONAL_TRADE_LESSONS.get(
        normalized_chapter,
        [],
    ):
        if str(
            lesson.get("id", "")
        ).strip() == normalized_lesson:
            return dict(lesson)
    return None
def get_quiz_questions(
    chapter_id: str,
    lesson_id: str,
) -> list[dict[str, Any]]:
    """Return quiz questions for a lesson."""
    key = (
        str(chapter_id).strip(),
        str(lesson_id).strip(),
    )
    return [
        dict(question)
        for question in INTERNATIONAL_TRADE_QUIZ_QUESTIONS.get(
            key,
            [],
        )
    ]
