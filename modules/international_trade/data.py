def validate_curriculum() -> bool:
    """
    Validate the basic structure of the curriculum.
    Returns:
        True when the curriculum structure is valid.
    """
    if not isinstance(
        INTERNATIONAL_TRADE_CURRICULUM,
        list,
    ):
        return False
    chapter_ids: set[str] = set()
    for chapter in INTERNATIONAL_TRADE_CURRICULUM:
        if not isinstance(
            chapter,
            dict,
        ):
            return False
        chapter_id = chapter.get("id")
        if not chapter_id:
            return False
        if chapter_id in chapter_ids:
            return False
        chapter_ids.add(
            chapter_id
        )
        lessons = chapter.get(
            "lessons"
        )
        if not isinstance(
            lessons,
            list,
        ):
            return False
        lesson_ids: set[str] = set()
        for lesson in lessons:
            if not isinstance(
                lesson,
                dict,
            ):
                return False
            lesson_id = lesson.get("id")
            if not lesson_id:
                return False
            if lesson_id in lesson_ids:
                return False
            lesson_ids.add(
                lesson_id
            )
            if not lesson.get("title"):
                return False
            if not lesson.get("content"):
                return False
            quiz = lesson.get(
                "quiz",
                [],
            )
            if not isinstance(
                quiz,
                list,
            ):
                return False
            for question in quiz:
                if not isinstance(
                    question,
                    dict,
                ):
                    return False
                if not question.get(
                    "question"
                ):
                    return False
                options = question.get(
                    "options"
                )
                if not isinstance(
                    options,
                    list,
                ):
                    return False
                if len(options) < 2:
                    return False
                answer = question.get(
                    "answer"
                )
                if not isinstance(
                    answer,
                    int,
                ):
                    return False
                if answer < 0 or answer >= len(options):
                    return False
    return True
