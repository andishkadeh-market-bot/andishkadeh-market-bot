def get_curriculum_statistics() -> dict[str, int]:
    """Return curriculum statistics."""
    chapters = len(
        INTERNATIONAL_TRADE_CURRICULUM
    )
    lessons = 0
    questions = 0
    for chapter in INTERNATIONAL_TRADE_CURRICULUM:
        chapter_id = str(
            chapter.get("id", "")
        ).strip()
        chapter_lessons = (
            INTERNATIONAL_TRADE_LESSONS.get(
                chapter_id,
                [],
            )
        )
        lessons += len(
            chapter_lessons
        )
        for lesson in chapter_lessons:
            lesson_id = str(
                lesson.get("id", "")
            ).strip()
            questions += len(
                INTERNATIONAL_TRADE_QUIZ_QUESTIONS.get(
                    (
                        chapter_id,
                        lesson_id,
                    ),
                    [],
                )
            )
    return {
        "chapters": chapters,
        "lessons": lessons,
        "questions": questions,
    }
def get_curriculum_stats() -> dict[str, int]:
    """Compatibility alias."""
    return get_curriculum_statistics()
