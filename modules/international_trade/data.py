# Search
# ==========================================================
def search_lessons(
    keyword: str,
) -> list[dict[str, Any]]:
    """Search lessons by title or content."""
    normalized_keyword = str(
        keyword or ""
    ).strip().casefold()
    if not normalized_keyword:
        return []
    result: list[dict[str, Any]] = []
    for chapter in INTERNATIONAL_TRADE_CURRICULUM:
        chapter_id = str(
            chapter.get("id", "")
        ).strip()
        for lesson in get_lessons(
            chapter_id
        ):
            title = str(
                lesson.get(
                    "title",
                    "",
                )
            )
            content = str(
                lesson.get(
                    "content",
                    "",
                )
            )
            searchable = (
                title + "\n" + content
            ).casefold()
            if normalized_keyword in searchable:
                result.append(
                    {
                        "module_id": MODULE_ID,
                        "chapter_id": chapter_id,
                        "lesson_id": lesson.get("id"),
                        "title": title,
                    }
                )
    return result
