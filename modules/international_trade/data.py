# Data Health Check
# ==========================================================
def data_health_check() -> bool:
    """
    Validate the International Trade data layer.
    """
    try:
        if not MODULE_ID:
            return False
        if not MODULE_TITLE:
            return False
        if not isinstance(
            INTERNATIONAL_TRADE_CURRICULUM,
            list,
        ):
            return False
        if len(
            INTERNATIONAL_TRADE_CURRICULUM
        ) != 16:
            return False
        chapter_ids: set[str] = set()
        for chapter in INTERNATIONAL_TRADE_CURRICULUM:
            if not isinstance(
                chapter,
                dict,
            ):
                return False
            chapter_id = chapter.get(
                "id"
            )
            title = chapter.get(
                "title"
            )
            description = chapter.get(
                "description"
            )
            if not chapter_id:
                return False
            if not title:
                return False
            if not description:
                return False
            if chapter_id in chapter_ids:
                return False
            chapter_ids.add(
                str(chapter_id)
            )
            if chapter_id not in INTERNATIONAL_TRADE_LESSONS:
                return False
            lessons = INTERNATIONAL_TRADE_LESSONS.get(
                chapter_id,
                [],
            )
            if not isinstance(
                lessons,
                list,
            ):
                return False
            lesson_ids: set[str] = set()
            for lesson in lessons:
                if not isinstance(
                    lesson,
                    dict,
                ):
                    return False
                lesson_id = lesson.get(
                    "id"
                )
                lesson_title = lesson.get(
                    "title"
                )
                content = lesson.get(
                    "content"
                )
                if not lesson_id:
                    return False
                if not lesson_title:
                    return False
                if not content:
                    return False
                if lesson_id in lesson_ids:
                    return False
                lesson_ids.add(
                    str(lesson_id)
                )
        for key, questions in INTERNATIONAL_TRADE_QUIZ_QUESTIONS.items():
            if not isinstance(
                key,
                tuple,
            ):
                return False
            if len(key) != 2:
                return False
            chapter_id, lesson_id = key
            if get_chapter(
                chapter_id
            ) is None:
                return False
            if get_lesson(
                chapter_id,
                lesson_id,
            ) is None:
                return False
            if not isinstance(
                questions,
                list,
            ):
                return False
            for question in questions:
                if not isinstance(
                    question,
                    dict,
                ):
                    return False
                if not question.get(
                    "id"
                ):
                    return False
                if not question.get(
                    "question"
                ):
                    return False
                options = question.get(
                    "options"
                )
                if not isinstance(
                    options,
                    list,
                ):
                    return False
                if len(options) < 2:
                    return False
                if question.get(
                    "correct_answer"
                ) not in options:
                    return False
        stats = get_curriculum_statistics()
        if stats["chapters"] != 16:
            return False
        if stats["lessons"] < 1:
            return False
        if stats["questions"] < 1:
            return False
        return True
    except Exception:
        return False
