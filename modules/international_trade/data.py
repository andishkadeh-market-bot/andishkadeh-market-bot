def get_curriculum_statistics() -> dict[str, int]:
    """Return curriculum statistics."""
    chapters = len(
        INTERNATIONAL_TRADE_CURRICULUM
    )
    lessons = sum(
        len(lessons)
        for lessons in INTERNATIONAL_TRADE_LESSONS.values()
    )
    questions = sum(
        len(questions)
        for questions in INTERNATIONAL_TRADE_QUIZ_QUESTIONS.values()
    )
    return {
        "modules": 1,
        "chapters": chapters,
        "lessons": lessons,
        "questions": questions,
        "quiz_questions": questions,
    }
def get_curriculum_stats() -> dict[str, int]:
    """Compatibility alias."""
    return get_curriculum_statistics()
