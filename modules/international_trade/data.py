# Health Check
# ==========================================================
def data_health_check() -> bool:
    """Validate International Trade data."""
    try:
        if not MODULE_ID:
            return False
        if not MODULE_TITLE:
            return False
        if not isinstance(
            INTERNATIONAL_TRADE_CURRICULUM,
            list,
        ):
            return False
        if len(
            INTERNATIONAL_TRADE_CURRICULUM
        ) != 16:
            return False
        chapter_ids: set[str] = set()
        for chapter in INTERNATIONAL_TRADE_CURRICULUM:
            if not isinstance(
                chapter,
                dict,
            ):
                return False
            chapter_id = str(
                chapter.get(
                    "id",
                    "",
                )
            ).strip()
            title = str(
                chapter.get(
                    "title",
                    "",
                )
            ).strip()
            if not chapter_id:
                return False
            if not title:
                return False
            if chapter_id in chapter_ids:
                return False
            chapter_ids.add(
                chapter_id
            )
            if chapter_id not in INTERNATIONAL_TRADE_LESSONS:
                return False
            lessons = INTERNATIONAL_TRADE_LESSONS.get(
                chapter_id,
                [],
            )
            if not isinstance(
                lessons,
                list,
            ):
                return False
            for lesson in lessons:
                if not isinstance(
                    lesson,
                    dict,
                ):
                    return False
                if not lesson.get(
                    "id"
                ):
                    return False
                if not lesson.get(
                    "title"
                ):
                    return False
                if not isinstance(
                    lesson.get(
                        "content",
                        "",
                    ),
                    str,
                ):
                    return False
        statistics = (
            get_curriculum_statistics()
        )
        if statistics["chapters"] != 16:
            return False
        if statistics["lessons"] < 1:
            return False
        if statistics["questions"] < 1:
            return False
        return True
    except Exception:
        return False
