def get_chapters() -> list[dict[str, Any]]:
    """Return all International Trade chapters."""
    return list(INTERNATIONAL_TRADE_CURRICULUM)


def get_chapter(
    chapter_id: str,
) -> dict[str, Any] | None:
    """Return one chapter by ID."""

    normalized_id = str(
        chapter_id or ""
    ).strip()

    for chapter in INTERNATIONAL_TRADE_CURRICULUM:
        if chapter.get("id") == normalized_id:
            return dict(chapter)

    return None


def get_lessons(
    chapter_id: str,
) -> list[dict[str, Any]]:
    """Return all lessons for a chapter."""

    normalized_id = str(
        chapter_id or ""
    ).strip()

    lessons = INTERNATIONAL_TRADE_LESSONS.get(
        normalized_id,
        [],
    )

    return [
        dict(lesson)
        for lesson in lessons
        if isinstance(lesson, dict)
    ]


def get_lesson(
    chapter_id: str,
    lesson_id: str,
) -> dict[str, Any] | None:
    """Return one lesson."""

    normalized_chapter_id = str(
        chapter_id or ""
    ).strip()

    normalized_lesson_id = str(
        lesson_id or ""
    ).strip()

    for lesson in INTERNATIONAL_TRADE_LESSONS.get(
        normalized_chapter_id,
        [],
    ):
        if lesson.get("id") == normalized_lesson_id:
            return dict(lesson)

    return None


def get_quiz_questions(
    chapter_id: str,
    lesson_id: str,
) -> list[dict[str, Any]]:
    """Return quiz questions for a lesson."""

    key = (
        str(chapter_id or "").strip(),
        str(lesson_id or "").strip(),
    )

    questions = INTERNATIONAL_TRADE_QUIZ_QUESTIONS.get(
        key,
        [],
    )

    return [
        dict(question)
        for question in questions
        if isinstance(question, dict)
    ]


# ==========================================================
# Curriculum Statistics
# ==========================================================

def get_curriculum_statistics() -> dict[str, int]:
    """Return curriculum statistics."""

    chapters = len(
        INTERNATIONAL_TRADE_CURRICULUM
    )

    lessons = 0
    questions = 0

    for chapter in INTERNATIONAL_TRADE_CURRICULUM:

        chapter_id = str(
            chapter.get("id") or ""
        ).strip()

        chapter_lessons = INTERNATIONAL_TRADE_LESSONS.get(
            chapter_id,
            [],
        )

        lessons += len(
            chapter_lessons
        )

        for lesson in chapter_lessons:

            lesson_id = str(
                lesson.get("id") or ""
            ).strip()

            questions += len(
                INTERNATIONAL_TRADE_QUIZ_QUESTIONS.get(
                    (
                        chapter_id,
                        lesson_id,
                    ),
                    [],
                )
            )

    return {
        "chapters": chapters,
        "lessons": lessons,
        "questions": questions,
        "quiz_questions": questions,
    }


