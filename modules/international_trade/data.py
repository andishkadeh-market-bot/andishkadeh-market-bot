# Additional Validation
# ==========================================================
def validate_curriculum() -> dict[str, Any]:
    """Return detailed curriculum validation information."""
    errors: list[str] = []
    warnings: list[str] = []
    chapter_ids: set[str] = set()
    for index, chapter in enumerate(
        INTERNATIONAL_TRADE_CURRICULUM,
        start=1,
    ):
        chapter_id = str(
            chapter.get("id", "")
        ).strip()
        if not chapter_id:
            errors.append(
                f"Chapter #{index} has no ID."
            )
            continue
        if chapter_id in chapter_ids:
            errors.append(
                f"Duplicate chapter ID: {chapter_id}"
            )
        chapter_ids.add(
            chapter_id
        )
        lessons = INTERNATIONAL_TRADE_LESSONS.get(
            chapter_id,
            [],
        )
        if not lessons:
            warnings.append(
                f"Chapter '{chapter_id}' has no lessons."
            )
        lesson_ids: set[str] = set()
        for lesson in lessons:
            lesson_id = str(
                lesson.get("id", "")
            ).strip()
            if not lesson_id:
                errors.append(
                    f"Chapter '{chapter_id}' contains lesson without ID."
                )
                continue
            if lesson_id in lesson_ids:
                errors.append(
                    (
                        f"Duplicate lesson ID '{lesson_id}' "
                        f"in chapter '{chapter_id}'."
                    )
                )
            lesson_ids.add(
                lesson_id
            )
            questions = (
                INTERNATIONAL_TRADE_QUIZ_QUESTIONS.get(
                    (
                        chapter_id,
                        lesson_id,
                    ),
                    [],
                )
            )
            if not questions:
                warnings.append(
                    (
                        f"Lesson '{lesson_id}' "
                        f"in chapter '{chapter_id}' has no quiz."
                    )
                )
    return {
        "valid": not errors,
        "errors": errors,
        "warnings": warnings,
        "statistics": get_curriculum_statistics(),
    }
