# ==========================================================

def search_lessons(
    keyword: str,
) -> list[dict[str, Any]]:
    """Search lessons by keyword."""

    normalized = str(
        keyword
    ).strip().casefold()

    if not normalized:
        return []

    results: list[
        dict[str, Any]
    ] = []

    for chapter in INTERNATIONAL_TRADE_CURRICULUM:

        chapter_id = str(
            chapter.get(
                "id",
                "",
            )
        )

        for lesson in get_lessons(
            chapter_id
        ):

            title = str(
                lesson.get(
                    "title",
                    "",
                )
            )

            content = str(
                lesson.get(
                    "content",
                    "",
                )
            )

            keywords = " ".join(
                str(item)
                for item in lesson.get(
                    "keywords",
                    [],
                )
            )

            searchable = (
                f"{title}\n"
                f"{content}\n"
                f"{keywords}"
            ).casefold()

            if normalized in searchable:

                results.append(
                    {
                        "module_id": MODULE_ID,
                        "chapter_id": chapter_id,
                        "lesson_id": lesson.get(
                            "id"
                        ),
                        "title": title,
                    }
                )

    return results


# ==========================================================
# Data Health Check
# ==========================================================

def data_health_check() -> bool:
    """Validate module data integrity."""

    try:

        if not MODULE_ID:
            return False

        if not MODULE_TITLE:
            return False

        if not isinstance(
            INTERNATIONAL_TRADE_CURRICULUM,
            list,
        ):
            return False

        if len(
            INTERNATIONAL_TRADE_CURRICULUM
        ) != 12:
            return False

        chapter_ids: set[str] = set()

        for chapter in INTERNATIONAL_TRADE_CURRICULUM:

            if not isinstance(
                chapter,
                dict,
            ):
                return False

            chapter_id = chapter.get(
                "id"
            )

            title = chapter.get(
                "title"
            )

            if not chapter_id or not title:
                return False

            chapter_id = str(
                chapter_id
            )

            if chapter_id in chapter_ids:
                return False

            chapter_ids.add(
                chapter_id
            )

            if chapter_id not in INTERNATIONAL_TRADE_LESSONS:
                return False

            lessons = INTERNATIONAL_TRADE_LESSONS.get(
                chapter_id,
                [],
            )

            if not isinstance(
                lessons,
                list,
            ):
                return False

            lesson_ids: set[str] = set()

            for lesson in lessons:

                if not isinstance(
                    lesson,
                    dict,
                ):
                    return False

                lesson_id = lesson.get(
                    "id"
                )

                lesson_title = lesson.get(
                    "title"
                )

                if not lesson_id:
                    return False

                if not lesson_title:
                    return False

                lesson_id = str(
                    lesson_id
                )

                if lesson_id in lesson_ids:
                    return False

                lesson_ids.add(
                    lesson_id
                )

                if "content" not in lesson:
                    return False

                questions = INTERNATIONAL_TRADE_QUIZ_QUESTIONS.get(
                    (
                        chapter_id,
                        lesson_id,
                    ),
                    [],
                )

                if not isinstance(
                    questions,
                    list,
                ):
                    return False

                for question in questions:

                    if not isinstance(
                        question,
                        dict,
                    ):
                        return False

                    if not question.get(
                        "id"
                    ):
                        return False

                    if not question.get(
                        "question"
                    ):
                        return False

                    options = question.get(
                        "options"
                    )

                    if not isinstance(
                        options,
                        list,
                    ):
                        return False

                    if len(
                        options
                    ) < 2:
                        return False

                    if not question.get(
                        "correct_answer"
                    ):
                        return False

        statistics = (
            get_curriculum_statistics()
        )

        if statistics["chapters"] != 12:
            return False

        if statistics["lessons"] < 1:
            return False

        if statistics["questions"] < 1:
            return False

        return True

    except Exception:
        return False


# ==========================================================
# Detailed Validation
# ==========================================================

def validate_module() -> dict[str, Any]:
    """Return detailed module validation."""

    errors: list[str] = []
    warnings: list[str] = []

    chapters = get_chapters()

    if not chapters:
        errors.append(
            "International Trade curriculum is empty."
        )

    chapter_ids: set[str] = set()

    for chapter_index, chapter in enumerate(
        chapters,
        start=1,
    ):

        chapter_id = str(
            chapter.get(
                "id",
                "",
            )
        ).strip()

        if not chapter_id:
            errors.append(
                f"Chapter #{chapter_index} has no ID."
            )
            continue

        if chapter_id in chapter_ids:
            errors.append(
                f"Duplicate chapter ID: {chapter_id}"
            )

        chapter_ids.add(
            chapter_id
        )

        lessons = get_lessons(
            chapter_id
        )

        if not lessons:
            warnings.append(
                f"Chapter '{chapter_id}' has no lessons."
            )

        lesson_ids: set[str] = set()

        for lesson_index, lesson in enumerate(
            lessons,
            start=1,
        ):

            lesson_id = str(
                lesson.get(
                    "id",
                    "",
                )
            ).strip()

            if not lesson_id:
                errors.append(
                    (
                        f"Chapter '{chapter_id}' "
                        f"lesson #{lesson_index} has no ID."
                    )
                )
                continue

            if lesson_id in lesson_ids:
                errors.append(
                    (
                        f"Duplicate lesson ID "
                        f"'{lesson_id}' in "
                        f"chapter '{chapter_id}'."
                    )
                )

            lesson_ids.add(
                lesson_id
            )

            if not lesson.get(
                "title"
            ):
                warnings.append(
                    (
                        f"Lesson '{lesson_id}' "
                        f"has no title."
                    )
                )

            if not lesson.get(
                "content"
            ):
                warnings.append(
                    (
                        f"Lesson '{lesson_id}' "
                        f"has no content."
                    )
                )

    statistics = (
        get_curriculum_statistics()
    )

    return {
        "valid": not errors,
        "errors": errors,
        "warnings": warnings,
        "statistics": statistics,
    }


