def get_chapters() -> list[dict[str, Any]]:
    """
    Return all banking chapters.
    """
    return CHAPTERS


def get_chapter(
    chapter_id: str,
) -> dict[str, Any] | None:
    """
    Return one chapter by ID.
    """
    for chapter in CHAPTERS:
        if chapter.get("id") == chapter_id:
            return chapter

    return None


def get_lessons(
    chapter_id: str,
) -> list[dict[str, Any]]:
    """
    Return lessons belonging to a chapter.
    """
    chapter = get_chapter(chapter_id)

    if chapter is None:
        return []

    lessons = chapter.get("lessons", [])

    if not isinstance(lessons, list):
        return []

    return lessons


def get_lesson(
    chapter_id: str,
    lesson_id: str,
) -> dict[str, Any] | None:
    """
    Return one lesson by chapter and lesson ID.
    """
    lessons = get_lessons(chapter_id)

    for lesson in lessons:
        if lesson.get("id") == lesson_id:
            return lesson

    return None


def get_module_info() -> dict[str, Any]:
    """
    Return module metadata.
    """
    return {
        "id": MODULE_ID,
        "title": MODULE_TITLE,
        "description": MODULE_DESCRIPTION,
        "version": MODULE_VERSION,
        "chapters": len(CHAPTERS),
    }


def get_curriculum_statistics() -> dict[str, int]:
    """
    Return curriculum statistics.
    """
    chapters_count = len(CHAPTERS)

    lessons_count = 0
    questions_count = 0

    for chapter in CHAPTERS:
        lessons = chapter.get("lessons", [])

        if not isinstance(lessons, list):
            continue

        lessons_count += len(lessons)

        for lesson in lessons:
            questions = lesson.get("questions", [])

            if isinstance(questions, list):
                questions_count += len(questions)

    return {
        "chapters": chapters_count,
        "lessons": lessons_count,
        "questions": questions_count,
    }


# ==========================================================
# Data Health Check
# ==========================================================

def data_health_check() -> bool:
    """
    Validate the Banking curriculum structure.
    """

    try:
        if not MODULE_ID:
            return False

        if not MODULE_TITLE:
            return False

        if not isinstance(
            CHAPTERS,
            list,
        ):
            return False

        if len(CHAPTERS) < 1:
            return False

        chapter_ids: set[str] = set()

        for chapter in CHAPTERS:

            if not isinstance(
                chapter,
                dict,
            ):
                return False

            chapter_id = chapter.get("id")
            chapter_title = chapter.get("title")
            lessons = chapter.get("lessons")

            if not chapter_id:
                return False

            if not chapter_title:
                return False

            if chapter_id in chapter_ids:
                return False

            chapter_ids.add(
                str(chapter_id)
            )

            if not isinstance(
                lessons,
                list,
            ):
                return False

            if len(lessons) < 1:
                return False

            lesson_ids: set[str] = set()

            for lesson in lessons:

                if not isinstance(
                    lesson,
                    dict,
                ):
                    return False

                lesson_id = lesson.get("id")
                lesson_title = lesson.get("title")
                content = lesson.get("content")

                if not lesson_id:
                    return False

                if not lesson_title:
                    return False

                if not isinstance(
                    content,
                    str,
                ):
                    return False

                if not content.strip():
                    return False

                if lesson_id in lesson_ids:
                    return False

                lesson_ids.add(
                    str(lesson_id)
                )

        return True

    except Exception:
        return False


