# Helpers
# ==========================================================

def get_chapters() -> list[dict[str, Any]]:
    """Return all banking chapters."""
    return CHAPTERS


def get_chapter(
    chapter_id: str,
) -> dict[str, Any] | None:
    """Return one banking chapter."""
    for chapter in CHAPTERS:
        if chapter.get("id") == chapter_id:
            return chapter

    return None


def get_lessons(
    chapter_id: str,
) -> list[dict[str, Any]]:
    """Return lessons belonging to a chapter."""
    chapter = get_chapter(chapter_id)

    if chapter is None:
        return []

    lessons = chapter.get("lessons", [])

    if not isinstance(lessons, list):
        return []

    return lessons


def get_lesson(
    chapter_id: str,
    lesson_id: str,
) -> dict[str, Any] | None:
    """Return one lesson."""
    for lesson in get_lessons(chapter_id):
        if lesson.get("id") == lesson_id:
            return lesson

    return None


def get_questions(
    chapter_id: str,
    lesson_id: str | None = None,
) -> list[dict[str, Any]]:
    """
    Return quiz questions.

    If lesson_id is supplied, only questions from that lesson
    are returned. Otherwise all questions in the chapter are returned.
    """

    lessons = get_lessons(chapter_id)

    result: list[dict[str, Any]] = []

    for lesson in lessons:

        if lesson_id is not None:
            if lesson.get("id") != lesson_id:
                continue

        questions = lesson.get("questions", [])

        if isinstance(questions, list):
            result.extend(
                q for q in questions
                if isinstance(q, dict)
            )

    return result


def get_all_questions() -> list[dict[str, Any]]:
    """Return every banking quiz question."""
    result: list[dict[str, Any]] = []

    for chapter in CHAPTERS:

        chapter_id = chapter.get("id")

        if not chapter_id:
            continue

        result.extend(
            get_questions(
                str(chapter_id)
            )
        )

    return result


def get_module_info() -> dict[str, Any]:
    """Return banking module metadata."""
    return {
        "id": MODULE_ID,
        "title": MODULE_TITLE,
        "description": MODULE_DESCRIPTION,
        "version": MODULE_VERSION,
        "chapters": len(CHAPTERS),
    }


def get_curriculum_statistics() -> dict[str, int]:
    """Return curriculum statistics."""

    chapters_count = len(CHAPTERS)
    lessons_count = 0
    questions_count = 0

    for chapter in CHAPTERS:

        lessons = chapter.get(
            "lessons",
            [],
        )

        if not isinstance(
            lessons,
            list,
        ):
            continue

        lessons_count += len(lessons)

        for lesson in lessons:

            questions = lesson.get(
                "questions",
                [],
            )

            if isinstance(
                questions,
                list,
            ):
                questions_count += len(questions)

    return {
        "chapters": chapters_count,
        "lessons": lessons_count,
        "questions": questions_count,
    }


