# Data Health Check
# ==========================================================

def data_health_check() -> bool:
    """
    Validate complete Banking curriculum.
    """

    try:

        if not MODULE_ID:
            return False

        if not MODULE_TITLE:
            return False

        if not isinstance(
            CHAPTERS,
            list,
        ):
            return False

        if len(CHAPTERS) < 1:
            return False

        chapter_ids: set[str] = set()

        for chapter in CHAPTERS:

            if not isinstance(
                chapter,
                dict,
            ):
                return False

            chapter_id = chapter.get(
                "id"
            )

            chapter_title = chapter.get(
                "title"
            )

            lessons = chapter.get(
                "lessons"
            )

            if not chapter_id:
                return False

            if not chapter_title:
                return False

            chapter_id = str(
                chapter_id
            )

            if chapter_id in chapter_ids:
                return False

            chapter_ids.add(
                chapter_id
            )

            if not isinstance(
                lessons,
                list,
            ):
                return False

            if len(lessons) < 1:
                return False

            lesson_ids: set[str] = set()

            for lesson in lessons:

                if not isinstance(
                    lesson,
                    dict,
                ):
                    return False

                lesson_id = lesson.get(
                    "id"
                )

                lesson_title = lesson.get(
                    "title"
                )

                content = lesson.get(
                    "content"
                )

                if not lesson_id:
                    return False

                if not lesson_title:
                    return False

                if not isinstance(
                    content,
                    str,
                ):
                    return False

                if not content.strip():
                    return False

                lesson_id = str(
                    lesson_id
                )

                if lesson_id in lesson_ids:
                    return False

                lesson_ids.add(
                    lesson_id
                )

                specialized_notes = lesson.get(
                    "specialized_notes",
                    [],
                )

                exam_notes = lesson.get(
                    "exam_notes",
                    [],
                )

                questions = lesson.get(
                    "questions",
                    [],
                )

                if not isinstance(
                    specialized_notes,
                    list,
                ):
                    return False

                if not isinstance(
                    exam_notes,
                    list,
                ):
                    return False

                if not isinstance(
                    questions,
                    list,
                ):
                    return False

                for quiz in questions:

                    if not isinstance(
                        quiz,
                        dict,
                    ):
                        return False

                    required_keys = {
                        "id",
                        "question",
                        "options",
                        "answer",
                        "correct_answer",
                        "explanation",
                    }

                    if not required_keys.issubset(
                        quiz.keys()
                    ):
                        return False

                    if not quiz.get(
                        "id"
                    ):
                        return False

                    if not quiz.get(
                        "question"
                    ):
                        return False

                    quiz_options = quiz.get(
                        "options"
                    )

                    if not isinstance(
                        quiz_options,
                        list,
                    ):
                        return False

                    if len(
                        quiz_options
                    ) != 4:
                        return False

                    option_ids: set[str] = set()

                    for option in quiz_options:

                        if not isinstance(
                            option,
                            dict,
                        ):
                            return False

                        option_id = option.get(
                            "id"
                        )

                        option_text = option.get(
                            "text"
                        )

                        if not option_id:
                            return False

                        if not option_text:
                            return False

                        option_id = str(
                            option_id
                        )

                        if option_id in option_ids:
                            return False

                        option_ids.add(
                            option_id
                        )

                    answer = str(
                        quiz.get(
                            "answer"
                        )
                    )

                    if answer not in option_ids:
                        return False

                    if str(
                        quiz.get(
                            "correct_answer"
                        )
                    ) != answer:
                        return False

                    if not quiz.get(
                        "explanation"
                    ):
                        return False

        statistics = get_curriculum_statistics()

        if statistics["chapters"] < 12:
            return False

        if statistics["lessons"] < 1:
            return False

        if statistics["questions"] < 1:
            return False

        return True

    except Exception:
        return False


