def get_accounting_chapters() -> list[dict[str, Any]]:
    """Return all accounting chapters."""
    return ACCOUNTING_CHAPTERS


def get_accounting_chapter(
    chapter_id: str,
) -> dict[str, Any] | None:
    """Return one accounting chapter."""
    for chapter in ACCOUNTING_CHAPTERS:
        if chapter["id"] == str(chapter_id):
            return chapter
    return None


def get_accounting_lessons(
    chapter_id: str,
) -> list[dict[str, Any]]:
    """Return lessons for a chapter."""
    chapter = get_accounting_chapter(chapter_id)

    if chapter is None:
        return []

    return chapter.get("lessons", [])


def get_accounting_lesson(
    chapter_id: str,
    lesson_id: str,
) -> dict[str, Any] | None:
    """Return one lesson."""
    for lesson in get_accounting_lessons(chapter_id):
        if lesson["id"] == str(lesson_id):
            return lesson

    return None


def get_accounting_quiz(
    chapter_id: str,
    lesson_id: str,
) -> list[dict[str, Any]]:
    """Return quiz questions for one lesson."""
    lesson = get_accounting_lesson(
        chapter_id,
        lesson_id,
    )

    if lesson is None:
        return []

    return lesson.get("quiz", [])


def get_all_accounting_quiz_questions() -> list[dict[str, Any]]:
    """Return all quiz questions from the complete curriculum."""
    questions: list[dict[str, Any]] = []

    for chapter in ACCOUNTING_CHAPTERS:
        for lesson in chapter.get("lessons", []):
            questions.extend(
                lesson.get("quiz", [])
            )

    return questions


def get_accounting_statistics() -> dict[str, int]:
    """Return curriculum statistics."""
    chapters = len(ACCOUNTING_CHAPTERS)

    lessons = sum(
        len(
            chapter.get(
                "lessons",
                [],
            )
        )
        for chapter in ACCOUNTING_CHAPTERS
    )

    quiz_questions = len(
        get_all_accounting_quiz_questions()
    )

    keywords = sum(
        len(
            lesson.get(
                "keywords",
                [],
            )
        )
        for chapter in ACCOUNTING_CHAPTERS
        for lesson in chapter.get(
            "lessons",
            [],
        )
    )

    return {
        "chapters": chapters,
        "lessons": lessons,
        "quiz_questions": quiz_questions,
        "keywords": keywords,
    }


def get_accounting_module_info() -> dict[str, Any]:
    """Return module metadata."""
    stats = get_accounting_statistics()

    return {
        "title": MODULE_TITLE,
        "description": MODULE_DESCRIPTION,
        "level": MODULE_LEVEL,
        "keywords": MODULE_KEYWORDS,
        "chapters": stats["chapters"],
        "lessons": stats["lessons"],
        "quiz_questions": stats["quiz_questions"],
    }


