def get_all_quiz_questions() -> list[dict]:
    questions: list[dict] = []

    for chapter in ACCOUNTING_CHAPTERS:
        for lesson in chapter.get("lessons", []):
            for question in lesson.get("quiz", []):
                item = dict(question)
                item["chapter_id"] = chapter["id"]
                item["lesson_id"] = lesson["id"]
                questions.append(item)

    return questions
