def check_management_answer(
    chapter,
    index,
    selected,
    score
):

    question = management_question_data(
        chapter,
        index
    )

    if question is None:
        return {
            "valid": False
        }

    correct = question["correct"]

    is_correct = selected == correct

    if is_correct:
        score += 1

    return {
        "valid": True,
        "correct": is_correct,
        "score": score,
        "correct_option": question["options"][correct],
        "explanation": question.get("explanation", ""),
    }


