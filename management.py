# 📘 متن فصل
# =========================================================

def management_chapter_text(chapter):

    if chapter not in MANAGEMENT_CHAPTER_NAMES:
        return (
            "❌ فصل موردنظر وجود ندارد.",
            management_back_menu()
        )

    name = MANAGEMENT_CHAPTER_NAMES[chapter]
    topics = MANAGEMENT_TOPICS.get(chapter, [])

    text = f"""
📘 فصل {chapter}

🏷️ {name}

━━━━━━━━━━━━━━━━━━

این فصل شامل {len(topics)} زیرموضوع است.

👇 زیرموضوع موردنظر را انتخاب کنید.
"""

    keyboard = []

    for index, topic in enumerate(topics):

        keyboard.append([
            InlineKeyboardButton(
                f"📖 {index + 1}. {topic}",
                callback_data=f"management_topic_{chapter}_{index}"
            )
        ])

    keyboard.append([
        InlineKeyboardButton(
            "📝 آزمون پایان فصل",
            callback_data=f"management_exam_intro_{chapter}"
        )
    ])

    keyboard.append([
        InlineKeyboardButton(
            "⬅️ فصل قبل",
            callback_data=(
                f"management_chapter_{chapter - 1}"
                if chapter > 1
                else "education"
            )
        ),
        InlineKeyboardButton(
            "فصل بعد ➡️",
            callback_data=(
                f"management_chapter_{chapter + 1}"
                if chapter < len(MANAGEMENT_CHAPTER_NAMES)
                else "education"
            )
        )
    ])

    keyboard.append([
        InlineKeyboardButton(
            "📚 آموزش مدیریت",
            callback_data="education"
        )
    ])

    keyboard.append([
        InlineKeyboardButton(
            "🏠 منوی اصلی",
            callback_data="home"
        )
    ])

    return text, InlineKeyboardMarkup(keyboard)


