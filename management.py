# 🏁 نتیجه آزمون
# =========================================================

def management_result_text(
    chapter,
    score
):

    questions = MANAGEMENT_QUESTIONS.get(
        chapter,
        []
    )

    total = len(questions)

    if total == 0:

        return "❌ آزمونی برای این فصل وجود ندارد."

    wrong = total - score

    percentage = round(
        (score / total) * 100
    )

    if percentage >= 90:

        evaluation = "🏆 فوق‌العاده"

        message = (
            "تسلط شما بر این فصل بسیار عالی است."
        )

    elif percentage >= 80:

        evaluation = "🥇 عالی"

        message = (
            "تسلط بسیار خوبی روی مباحث فصل دارید."
        )

    elif percentage >= 70:

        evaluation = "🥈 خوب"

        message = (
            "تسلط مناسبی دارید، اما مرور بیشتر مفید است."
        )

    elif percentage >= 50:

        evaluation = "🟡 متوسط"

        message = (
            "بعضی مفاهیم نیاز به مطالعه و تمرین بیشتری دارند."
        )

    else:

        evaluation = "📚 نیازمند مطالعه"

        message = (
            "پیشنهاد می‌شود ابتدا درسنامه را دوباره مطالعه کنید."
        )

    name = CHAPTER_NAMES.get(
        chapter,
        "مدیریت"
    )

    return f"""
🏁 آزمون فصل {chapter} به پایان رسید.

🧠 {name}

━━━━━━━━━━━━━━━━━━

📊 نتیجه آزمون

📝 تعداد سؤالات: {total}

✅ پاسخ صحیح: {score}

❌ پاسخ غلط: {wrong}

📈 درصد: {percentage}٪

🎯 ارزیابی:
{evaluation}

━━━━━━━━━━━━━━━━━━

💡 {message}

━━━━━━━━━━━━━━━━━━

🎯 مسیر یادگیری:

مطالعه
+
آزمون
+
تحلیل اشتباهات
+
مرور
"""


