def management_question_data(
    chapter,
    index,
    score
):

    questions = MANAGEMENT_QUESTIONS.get(
        chapter,
        []
    )

    if index >= len(questions):

        return None

    question = questions[index]

    text = f"""
📝 آزمون مدیریت

📘 فصل {chapter}
🧠 {CHAPTER_NAMES.get(chapter, "مدیریت")}

━━━━━━━━━━━━━━━━━━

❓ سؤال {index + 1} از {len(questions)}

⭐ امتیاز فعلی: {score}

━━━━━━━━━━━━━━━━━━

{question["question"]}

━━━━━━━━━━━━━━━━━━

👇 گزینه صحیح را انتخاب کنید:
"""

    keyboard = []

    for option_index, option in enumerate(
        question["options"]
    ):

        keyboard.append(
            [
                InlineKeyboardButton(
                    option,
                    callback_data=(
                        f"management_answer_"
                        f"{chapter}_"
                        f"{index}_"
                        f"{option_index}_"
                        f"{score}"
                    )
                )
            ]
        )

    keyboard.append(
        [
            InlineKeyboardButton(
                "🧠 خروج از آزمون",
                callback_data="management"
            )
        ]
    )

    return (
        text,
        InlineKeyboardMarkup(keyboard)
    )


