# =========================================================

def management_question_text(chapter, index, score):

    question = management_question_data(
        chapter,
        index
    )

    questions = MANAGEMENT_QUESTIONS.get(chapter, [])

    if question is None:
        return (
            "❌ سؤال موردنظر وجود ندارد.",
            management_back_menu()
        )

    text = f"""
📝 آزمون مدیریت

📘 فصل {chapter}
🏷️ {MANAGEMENT_CHAPTER_NAMES[chapter]}

━━━━━━━━━━━━━━━━━━

❓ سؤال {index + 1} از {len(questions)}

⭐ امتیاز فعلی: {score}

━━━━━━━━━━━━━━━━━━

{question["question"]}

━━━━━━━━━━━━━━━━━━

👇 گزینه موردنظر را انتخاب کنید.
"""

    keyboard = []

    for option_index, option in enumerate(
        question["options"]
    ):

        keyboard.append([
            InlineKeyboardButton(
                option,
                callback_data=(
                    f"management_answer_"
                    f"{chapter}_"
                    f"{index}_"
                    f"{option_index}_"
                    f"{score}"
                )
            )
        ])

    keyboard.append([
        InlineKeyboardButton(
            "📚 خروج از آزمون",
            callback_data="education"
        )
    ])

    return text, InlineKeyboardMarkup(keyboard)


