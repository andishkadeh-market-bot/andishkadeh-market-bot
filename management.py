# =========================================================

def management_answer_data(
    chapter,
    index,
    selected,
    score
):

    questions = MANAGEMENT_QUESTIONS.get(
        chapter,
        []
    )

    if not questions:

        return None

    if index < 0 or index >= len(questions):

        return None

    question = questions[index]

    correct = question["correct"]

    if selected == correct:

        score += 1

        result_text = f"""
✅ پاسخ صحیح است.

🎯 +۱ امتیاز

⭐ امتیاز فعلی: {score}

━━━━━━━━━━━━━━━━━━

آفرین 👏

مفهوم این سؤال را به‌خوبی تشخیص دادید.
"""

    else:

        correct_option = question["options"][correct]

        result_text = f"""
❌ پاسخ صحیح نیست.

━━━━━━━━━━━━━━━━━━

✅ پاسخ صحیح:

{correct_option}

━━━━━━━━━━━━━━━━━━

⭐ امتیاز فعلی: {score}

💡 پیشنهاد:

مفهوم مربوط به این سؤال را
یک بار دیگر مرور کنید.
"""

    next_index = index + 1

    finished = (
        next_index >= len(questions)
    )

    return {

        "score": score,

        "next_index": next_index,

        "result_text": result_text,

        "finished": finished,

    }


