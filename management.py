# ✅ داده پاسخ
#
# این تابع برای سازگاری با bot.py اضافه شده است.
# =========================================================

def management_answer_data(
    chapter,
    index,
    selected,
    score
):

    question = management_question_data(
        chapter,
        index
    )

    if question is None:
        return {
            "valid": False
        }

    correct = question["correct"]

    is_correct = selected == correct

    new_score = score + 1 if is_correct else score

    return {
        "valid": True,
        "correct": is_correct,
        "score": new_score,
        "correct_option": question["options"][correct],
        "explanation": question.get(
            "explanation",
            ""
        ),
        "question": question,
    }


# =========================================================
# ✅ بررسی پاسخ
# =========================================================

def check_management_answer(
    chapter,
    index,
    selected,
    score
):

    return management_answer_data(
        chapter,
        index,
        selected,
        score
    )


