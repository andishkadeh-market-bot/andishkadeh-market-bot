def management_menu():

    keyboard = []

    for chapter, name in CHAPTER_NAMES.items():

        keyboard.append(
            [
                InlineKeyboardButton(
                    f"📘 فصل {chapter}: {name}",
                    callback_data=f"management_chapter_{chapter}"
                )
            ]
        )

    keyboard.extend(
        [

            [
                InlineKeyboardButton(
                    "🏠 منوی اصلی",
                    callback_data="home"
                )
            ],

        ]
    )

    return InlineKeyboardMarkup(keyboard)


