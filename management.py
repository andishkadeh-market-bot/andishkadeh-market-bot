def management_exam_result_text(chapter, score):

    questions = MANAGEMENT_QUESTIONS.get(chapter, [])

    total = len(questions)

    if total == 0:
        return (
            "❌ آزمونی برای این فصل وجود ندارد.",
            management_back_menu()
        )

    score = max(
        0,
        min(score, total)
    )

    wrong = total - score

    percentage = round(
        (score / total) * 100
    )

    if percentage >= 90:

        evaluation = "🏆 فوق‌العاده"
        message = "تسلط شما بر این فصل بسیار عالی است."

    elif percentage >= 80:

        evaluation = "🥇 عالی"
        message = "تسلط بسیار خوبی روی مباحث دارید."

    elif percentage >= 70:

        evaluation = "🥈 خوب"
        message = "وضعیت خوبی دارید، اما مرور بیشتر مفید است."

    elif percentage >= 50:

        evaluation = "🟡 متوسط"
        message = "برخی مفاهیم نیاز به مطالعه و تمرین بیشتری دارند."

    else:

        evaluation = "📚 نیازمند مطالعه"
        message = "پیشنهاد می‌شود درسنامه را دوباره مطالعه کنید."

    text = f"""
🏁 آزمون فصل {chapter} به پایان رسید.

📚 {MANAGEMENT_CHAPTER_NAMES[chapter]}

━━━━━━━━━━━━━━━━━━

📊 نتیجه آزمون

📝 تعداد سؤالات: {total}

✅ پاسخ صحیح: {score}

❌ پاسخ غلط: {wrong}

📈 درصد: {percentage}٪

🎯 ارزیابی:

{evaluation}

━━━━━━━━━━━━━━━━━━

💡 {message}

━━━━━━━━━━━━━━━━━━

🎯 مسیر پیشنهادی:

مطالعه
⬇️
آزمون
⬇️
تحلیل اشتباهات
⬇️
مرور
⬇️
آزمون مجدد
"""

    keyboard = [

        [
            InlineKeyboardButton(
                "🔄 تکرار آزمون",
                callback_data=f"management_exam_{chapter}_0_0"
            )
        ],

        [
            InlineKeyboardButton(
                "📖 مرور فصل",
                callback_data=f"management_chapter_{chapter}"
            )
        ],
    ]

    if chapter < len(MANAGEMENT_CHAPTER_NAMES):

        keyboard.append([
            InlineKeyboardButton(
                f"📘 فصل بعد: {chapter + 1}",
                callback_data=f"management_chapter_{chapter + 1}"
            )
        ])

    keyboard.extend([

        [
            InlineKeyboardButton(
                "📚 آموزش مدیریت",
                callback_data="education"
            )
        ],

        [
            InlineKeyboardButton(
                "🏠 منوی اصلی",
                callback_data="home"
            )
        ],

    ])

    return text, InlineKeyboardMarkup(keyboard)


