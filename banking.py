# 📊 ارزیابی نتیجه
# =========================================================

def evaluate_score(score, total):

    if total == 0:

        return "⚪ بدون نتیجه"

    percentage = round(
        (score / total) * 100
    )

    if percentage >= 90:

        return "🏆 فوق‌العاده"

    if percentage >= 80:

        return "🥇 عالی"

    if percentage >= 70:

        return "🥈 خوب"

    if percentage >= 60:

        return "🟡 قابل قبول"

    if percentage >= 50:

        return "🟠 نیاز به مرور"

    return "🔴 نیاز به مطالعه بیشتر"


