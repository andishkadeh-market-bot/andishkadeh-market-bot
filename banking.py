def banking_chapter_text(chapter):

    text = BANKING_CHAPTER_TEXTS.get(chapter)

    if not text:

        return (
            "❌ فصل موردنظر پیدا نشد.",
            banking_back_menu()
        )

    keyboard = [

        [
            InlineKeyboardButton(
                "📝 آزمون این فصل",
                callback_data=f"banking_exam_intro_{chapter}"
            )
        ],

        [
            InlineKeyboardButton(
                "⬅️ فصل قبل",
                callback_data=(
                    f"banking_chapter_{chapter - 1}"
                    if chapter > 1
                    else "banking"
                )
            ),

            InlineKeyboardButton(
                "فصل بعد ➡️",
                callback_data=(
                    f"banking_chapter_{chapter + 1}"
                    if chapter < 12
                    else "banking"
                )
            )
        ],

        [
            InlineKeyboardButton(
                "🏦 بانکداری",
                callback_data="banking"
            )
        ],

        [
            InlineKeyboardButton(
                "🏠 منوی اصلی",
                callback_data="home"
            )
        ],

    ]

    return text, InlineKeyboardMarkup(keyboard)


