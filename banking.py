# سؤال آزمون
# =========================================================

def banking_exam_question(
    chapter,
    index=0,
    score=0
):

    questions = BANKING_CHAPTER_QUESTIONS.get(
        chapter,
        []
    )

    if not questions:

        return (
            "❌ برای این فصل سؤالی ثبت نشده است.",
            banking_back_menu()
        )

    if index >= len(questions):

        index = 0

    question = questions[index]

    text = f"""
📝 آزمون بانکداری

📘 فصل {chapter}
🏦 {CHAPTER_NAMES.get(chapter, "بانکداری")}

━━━━━━━━━━━━━━━━━━

❓ سؤال {index + 1} از {len(questions)}

⭐ امتیاز فعلی: {score}

━━━━━━━━━━━━━━━━━━

{question["question"]}

━━━━━━━━━━━━━━━━━━

👇 گزینه موردنظر را انتخاب کنید:
"""

    keyboard = []

    for option_index, option in enumerate(
        question["options"]
    ):

        keyboard.append([
            InlineKeyboardButton(
                option,
                callback_data=(
                    f"banking_answer_"
                    f"{chapter}_"
                    f"{index}_"
                    f"{option_index}_"
                    f"{score}"
                )
            )
        ])

    keyboard.append([
        InlineKeyboardButton(
            "🏦 خروج از آزمون",
            callback_data="banking"
        )
    ])

    return text, InlineKeyboardMarkup(keyboard)


