# =========================================================
# 🏦 منوی بانکداری
# =========================================================

def banking_menu():

    keyboard = []

    for chapter, name in CHAPTER_NAMES.items():

        keyboard.append([
            InlineKeyboardButton(
                f"{CHAPTER_ICONS.get(chapter, '📚')} "
                f"فصل {chapter} | {name}",
                callback_data=f"banking_chapter_{chapter}"
            )
        ])

    keyboard.append([
        InlineKeyboardButton(
            "🏆 آزمون جامع بانکداری",
            callback_data="banking_full_exam"
        )
    ])

    keyboard.append([
        InlineKeyboardButton(
            "🏠 منوی اصلی",
            callback_data="home"
        )
    ])

    return InlineKeyboardMarkup(keyboard)


