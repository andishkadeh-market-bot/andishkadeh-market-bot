# 🏁 نتیجه آزمون فصل
# =========================================================

def banking_exam_result(chapter, score):

    questions = BANKING_CHAPTER_QUESTIONS.get(chapter, [])

    total = len(questions)

    if total == 0:
        return "❌ آزمونی برای این فصل وجود ندارد.", banking_back_menu()

    wrong = total - score
    percentage = round((score / total) * 100)

    if percentage >= 90:
        evaluation = "🏆 فوق‌العاده"
        message = "تسلط شما بر این فصل بسیار عالی است."

    elif percentage >= 80:
        evaluation = "🥇 عالی"
        message = "تسلط بسیار خوبی روی مباحث فصل دارید."

    elif percentage >= 70:
        evaluation = "🥈 خوب"
        message = "تسلط مناسبی دارید، اما مرور فصل پیشنهاد می‌شود."

    elif percentage >= 50:
        evaluation = "🥉 متوسط"
        message = "بعضی مفاهیم نیاز به مرور و تمرین بیشتری دارند."

    else:
        evaluation = "📚 نیازمند مطالعه"
        message = "پیشنهاد می‌شود درسنامه فصل را دوباره مطالعه کنید."

    next_chapter = chapter + 1

    text = f"""
🏁 آزمون فصل {chapter} به پایان رسید.

🏦 {CHAPTER_NAMES[chapter]}

━━━━━━━━━━━━━━━━━━

📊 نتیجه آزمون

📝 تعداد سؤالات: {total}

✅ پاسخ صحیح: {score}

❌ پاسخ غلط: {wrong}

📈 درصد: {percentage}٪

🎯 ارزیابی: {evaluation}

━━━━━━━━━━━━━━━━━━

💡 {message}

━━━━━━━━━━━━━━━━━━
"""

    keyboard = []

    if next_chapter <= 12:
        keyboard.append([
            InlineKeyboardButton(
                f"📘 ورود به فصل {next_chapter}",
                callback_data=f"banking_chapter_{next_chapter}"
            )
        ])

    keyboard.append([
        InlineKeyboardButton(
            "🏦 بازگشت به بانکداری",
            callback_data="banking"
        )
    ])

    keyboard.append([
        InlineKeyboardButton(
            "🏠 منوی اصلی",
            callback_data="home"
        )
    ])

    return text, InlineKeyboardMarkup(keyboard)


