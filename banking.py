def banking_exam_question(chapter, index=0, score=0):

    questions = BANKING_CHAPTER_QUESTIONS.get(chapter, [])

    if not questions:
        return "❌ سوالی برای این فصل وجود ندارد.", banking_back_menu()

    if index >= len(questions):
        index = 0

    question = questions[index]

    text = f"""
📝 آزمون بانکداری

📘 فصل {chapter} | {CHAPTER_NAMES[chapter]}

━━━━━━━━━━━━━━━━━━

سؤال {index + 1} از {len(questions)}

⭐ امتیاز فعلی: {score}

━━━━━━━━━━━━━━━━━━

{question["question"]}

👇 پاسخ صحیح را انتخاب کنید:
"""

    keyboard = []

    for i, option in enumerate(question["options"]):
        keyboard.append([
            InlineKeyboardButton(
                option,
                callback_data=f"banking_answer_{chapter}_{index}_{i}_{score}"
            )
        ])

    return text, InlineKeyboardMarkup(keyboard)


